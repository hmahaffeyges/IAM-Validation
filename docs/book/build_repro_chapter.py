"""Writes part6/p6_20c_reproduced.tex, "The commissioning record, reproduced" (2026-10-19, author: "Are those tests in the book yet? with the
report as a visual"). Section 1 shows a real chain v4 report page by page (images rendered from the committed researcher PDFs in
doors/data/REPORT_EXAMPLES_V4/final). Section 2 lists every test in Biological_Physics/MethylPhys/reproduce/tests.json with its fresh-clone result from
Biological_Physics/MethylPhys/reproduce/verified.json. Nothing is typed by hand: rerun after either file changes. --check: refuse if the chapter differs."""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); REPO = os.path.abspath(os.path.join(HERE, "..", ".."))
OUT = os.path.join(HERE, "part6", "p6_20c_reproduced.tex"); FIG = os.path.join(HERE, "figures", "part6")
FINAL = os.path.join(REPO, "Biological_Physics", "MethylPhys", "doors", "data", "REPORT_EXAMPLES_V4", "final")
GH = "https://github.com/hmahaffeyges/IAM-Validation/blob/main/"
def tex(s):
    for a, b in (("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"), ("$", r"\$"), ("#", r"\#"), ("_", r"\_"), ("{", r"\{"), ("}", r"\}"),
                 ("~", r"\textasciitilde{}"), ("^", r"\textasciicircum{}"), ("≤", r"$\le$"), ("≥", r"$\ge$"), ("×", r"$\times$"), ("–", "--")):
        s = s.replace(a, b)
    return s
PAGES = [("blood", 1, "fig_p6_report_blood_p1", "Healthy whole blood (GSE235717, GSM7508429), page 1: the reading of every instrument at a glance, each "
          "with its commissioning status (Met-A's whole-blood reading is labeled preliminary), and the physics behind each reading."),
         ("blood", 2, "fig_p6_report_blood_p2", "Page 2: the cell shares from the IAM-Deconvolver against IAM-Atlas v2.1, each with its range and status (NK and "
          "B cells are labeled preliminary), then Met-A on its gauge and the C-Score on its bar."),
         ("blood", 3, "fig_p6_report_blood_p3", "Page 3: what changed, the sample laid over its healthy reference on the HEALPix sphere. Gray is where the "
          "sample matches healthy neutrophils from IAM-Atlas v2.1; color marks only the sites that differ from healthy by more than 2 of the "
          "sample's own spread."),
         ("cd8", 1, "fig_p6_report_cd8_p1", "Healthy CD8 T cells by sequencing (GSM4293895), page 1: IAM-A read against the sample's own "
          "reference (A 0.9083, Normal, commissioned): the held error, the loose share and what the healthy line predicts from it."),
         ("cd8", 2, "fig_p6_report_cd8_p2", "Page 2: IAM-A on its gauge.")]
PDF = {"blood": "GSE235717_GSM7508429_researcher.pdf", "cd8": "GSM4293895_CD8_researcher.pdf"}
def render():
    import pypdfium2 as P
    from PIL import ImageChops, Image
    for tag, k, name, _ in PAGES:
        im = P.PdfDocument(os.path.join(FINAL, PDF[tag]))[k - 1].render(scale=2).to_pil().convert("RGB")
        box = ImageChops.difference(im, Image.new("RGB", im.size, "white")).getbbox()
        if box: im = im.crop((max(box[0] - 30, 0), max(box[1] - 30, 0), min(box[2] + 30, im.width), min(box[3] + 30, im.height)))
        im.save(os.path.join(FIG, name + ".png"), optimize=True)
def text():
    T = json.load(open(os.path.join(REPO, "Biological_Physics", "MethylPhys", "reproduce", "tests.json"), encoding="utf-8"))["tests"]
    V = json.load(open(os.path.join(REPO, "Biological_Physics", "MethylPhys", "reproduce", "verified.json"), encoding="utf-8"))
    L = [r"\chapter{The commissioning record, reproduced}\label{ch:reproduced}", "",
         r"% Generated by docs/book/build_repro_chapter.py from Biological_Physics/MethylPhys/reproduce/tests.json, Biological_Physics/MethylPhys/reproduce/verified.json and the committed reports. Do not edit.", "",
         "This chapter shows two things a reader can check without taking anything on trust: what a report from the commissioned chain looks "
         "like, and every headline result rebuilt from public data by one command on a machine that had never seen the work.", "",
         r"\section{A report, page by page}", "",
         "The pages below are the researcher view of two real reports, exactly as the chain wrote them (Chapter~\\ref{ch:walkthrough} reads "
         "them step by step). An array report carries every instrument that reads arrays; a sequencing report carries IAM-A. Each reading is "
         "printed with its commissioning status, and a reading outside what an instrument was tested on is shown and labeled preliminary.", ""]
    for tag, k, name, cap in PAGES:
        L += [r"\begin{figure}[p]\centering", rf"\includegraphics[width=0.92\textwidth,height=0.82\textheight,keepaspectratio]{{figures/part6/{name}.png}}",
              rf"\caption{{{tex(cap)}}}\label{{fig:report:{tag}{k}}}", r"\end{figure}", ""]
    done = [t for t in T if (V.get(t["id"]) or {}).get("verdict") == "PASS"]
    L += [r"\clearpage", r"\section{Every result, rebuilt from public data}", "",
          "Each test below is one entry in the repository's reproduction registry (Biological\\_Physics/MethylPhys/reproduce/tests.json). The command "
          r"\texttt{python3 Biological\_Physics/MethylPhys/reproduce/reproduce.py <test>} downloads only public files (GEO, ArrayExpress, ENCODE, the NCI Genomic Data "
          "Commons, ENA, Zenodo), runs the steps, and compares every number with the committed result, taken from git so a script cannot "
          "compare a file with itself. Each was run from a fresh clone of the public repository on a new machine.",
          f" {len(done)} of the {len(T)} tests have passed that way with every compared number identical.", "",
          r"\begin{center}\small\begin{tabular}{p{0.34\textwidth}p{0.22\textwidth}p{0.12\textwidth}p{0.18\textwidth}}\hline",
          r"\textbf{Test} & \textbf{Instrument} & \textbf{Checks} & \textbf{Fresh-clone result}\\\hline"]
    for t in T:
        v = V.get(t["id"]) or {}
        res = f"{v['verdict']}, {v['date']}" if v.get("verdict") else "not yet recorded"
        chk = f"{v['checks_ok']} of {v['checks']}" if v.get("checks") else "--"
        L.append(rf"\texttt{{{tex(t['id'])}}} & {tex(t.get('instrument', ''))} & {chk} & {res}\\")
    L += [r"\hline\end{tabular}\end{center}", ""]
    for t in T:
        v = V.get(t["id"]) or {}
        L += [rf"\subsection*{{{tex(t['title'])}}}", "", tex(t.get("shows", "")), "",
              r"\begin{itemize}\setlength\itemsep{1pt}",
              rf"\item \textbf{{Public data:}} {tex('; '.join(t.get('public_inputs', [])))}.",
              rf"\item \textbf{{Command:}} \texttt{{python3 Biological\_Physics/MethylPhys/reproduce/reproduce.py {tex(t['id'])}}} ({tex(t.get('time', ''))}; {tex(t.get('disk', ''))} of disk"
              + (f"; {tex(t['memory'])} of memory" if t.get("memory") else "") + ").",
              (rf"\item \textbf{{Fresh-clone result:}} {v['verdict']} on {v['date']}, {v['checks_ok']} of {v['checks']} compared numbers identical, "
               rf"{round(v['minutes'])} minutes, repository commit \texttt{{{tex(v['commit'])}}}." if v.get("verdict") else
               r"\item \textbf{Fresh-clone result:} not yet recorded."),
              rf"\item \textbf{{Record:}} \url{{{GH}{t['record']}}}", r"\end{itemize}", ""]
    return "\n".join(L) + "\n"
if __name__ == "__main__":
    t = text()
    if "--check" in sys.argv:
        ok = os.path.exists(OUT) and open(OUT, encoding="utf-8").read() == t and all(os.path.exists(os.path.join(FIG, p[2] + ".png")) for p in PAGES)
        import re as _re   # 2026-10-19: a raw underscore outside math, a comment or a url broke the book build
        _b = _re.sub(r"\\(url|includegraphics|label|ref)(\[[^]]*\])?\{[^}]*\}", "", _re.sub(r"(?m)(?<!\\)%.*$", "", t))
        if _re.search(r"(?<!\\)_", _re.sub(r"\$[^$]*\$", "", _b)): ok = False; print("repro_chapter: an unescaped underscore would break the book build")
        print("repro_chapter: " + ("ok" if ok else "REFUSED: the reproduced chapter differs (run python3 docs/book/build_repro_chapter.py)")); sys.exit(0 if ok else 1)
    render(); open(OUT, "w", encoding="utf-8").write(t); print("repro_chapter: written")
