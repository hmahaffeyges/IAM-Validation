# ---------------------------------------------------------------- the sky run: six neutrophil arrays
stats = list(csv.DictReader(open(SKY / "sky_neut6_stats.csv")))
arrays = sorted({r["array"] for r in stats if r["map"] == "healthy"})
assert len(arrays) == 6, arrays
maps = {r["map"] for r in stats}
assert {"healthy", "blur2pct", "local5pct", "null"} <= maps, maps
def rng(m, col):
    v = [float(r[col]) for r in stats if r["map"] == m]
    assert len(v) == 6, (m, col, len(v))
    return min(v), max(v)
