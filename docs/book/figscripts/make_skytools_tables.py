L = [r"% generated by docs/book/figscripts/make_skytools_tables.py from reference_floors_v1/sky/sky_neut6_stats.csv; do not edit by hand",
     r"\begin{center}\small", r"\begin{tabular}{@{}lcc@{}}\toprule", r"specimen & Met-A & C-score \\\midrule"]
for m, name in SPEC:
    a, c = rng(m, "MetA_6000"), rng(m, "C_6000")
    L.append(f"{name} & {a[0]:.3f}--{a[1]:.3f} & {c[0]:.2f}--{c[1]:.2f} \\\\")
L += [r"\bottomrule\end{tabular}", r"\end{center}"]
OUT_STATS.write_text("\n".join(L) + "\n")

