#!/usr/bin/env python3
"""The book's chapter "IAM in bits" (author 2026-10-16: the four domains and the bit tables belong in the book, the repo and the page),
generated from CANON/four_domains.json through CANON/bit_tables.py's rows; nothing is typed here. Each computer term lists the four
applications' own words with the book's status. Writes docs/book/part7/p7_08b_bits.tex. --check refuses drift."""
import os, sys
H = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(H); sys.path.insert(0, H); import bit_tables as BT
OUT = os.path.join(ROOT, "docs", "book", "part7", "p7_08b_bits.tex")
def tex(t):
    t = str(t or "")
    for a, b in (("\\\\", "\\textbackslash{}"), ("&", "\\&"), ("%", "\\%"), ("$", "\\$"), ("#", "\\#"), ("_", "\\_"), ("{", "\\{"), ("}", "\\}"), ("~", "\\textasciitilde{}"), ("^", "\\textasciicircum{}")):
        t = t.replace(a, b)
    return t
L = ["% Generated by CANON/book_bits.py from CANON/four_domains.json; do not edit by hand.", "\\chapter{IAM in bits}", "\\label{ch:bits}", "",
     "\\textbf{IAM is a model of how reality begins with a bit and the cost that comes with it.} This chapter is the connections table: one",
     "computer term per row, and in each of the four applications the word that application uses for it, with the status this book gives it.",
     "The same table, with every value and its source, is \\texttt{development/bit\\_paper/BIT\\_TABLES.md}; the four-domain schematic it is drawn",
     "from is \\texttt{FOUR\\_DOMAINS.md}. \\emph{Open} means no value has been found yet.", ""]
for term, k, mean in BT.ROWS:
    L += [f"\\section*{{{tex(term)}}}", f"\\emph{{{tex(mean)}.}}", "\\begin{description}"]
    for d in BT.DOM:
        e = BT.S[k][d]; L.append(f"\\item[{BT.NAME[d]}] {tex(BT.short(e.get('native') or e.get('formula'), 220))} \\hfill(\\textit{{{tex(e.get('status'))}}})")
    L += ["\\end{description}", ""]
txt = "\n".join(L) + "\n"
if "--check" in sys.argv:
    ok = os.path.exists(OUT) and open(OUT, encoding="utf-8").read() == txt
    print("book_bits: " + ("ok" if ok else "REFUSED: docs/book/part7/p7_08b_bits.tex differs (run python3 CANON/book_bits.py)")); sys.exit(0 if ok else 1)
open(OUT, "w", encoding="utf-8").write(txt); print("book_bits: wrote", len(BT.ROWS), "terms x", len(BT.DOM), "applications")
