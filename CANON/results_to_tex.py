#!/usr/bin/env python3
"""results_to_tex.py - write the book's development chapter (docs/book/part6/p6_25_development.tex) and the Advancements table of
Biological_Physics/README.md (between the ADVANCEMENTS markers) from CANON/results_register.json. Every number is recomputed from the committed
record files. Run: python3 CANON/results_to_tex.py   (write)   |   build() returns (tex, readme_block) for CANON/status_check.py."""
import os, re, json, csv, itertools, statistics as st
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
TEX = os.path.join(ROOT, "docs/book/part6/p6_25_development.tex"); README = os.path.join(ROOT, "Biological_Physics/README.md")
B, E = "<!-- ADVANCEMENTS:BEGIN (generated by CANON/results_to_tex.py from CANON/results_register.json; do not edit by hand) -->", "<!-- ADVANCEMENTS:END -->"
def rows(p): return list(csv.DictReader(open(os.path.join(ROOT, p), encoding="utf-8")))
def mw_p_greater(x, y):
    """Exact one-sided Mann-Whitney p (x larger than y), by enumerating every split of the pooled values."""
    pool = list(x) + list(y); n = len(x)
    def stat(idx):
        a = [pool[i] for i in idx]; b = [pool[i] for i in range(len(pool)) if i not in idx]
        return sum((ai > bj) + 0.5 * (ai == bj) for ai in a for bj in b)
    obs = stat(tuple(range(n))); allc = list(itertools.combinations(range(len(pool)), n))
    return sum(stat(c) >= obs - 1e-12 for c in allc) / len(allc)
def f3(x): return f"{x:.3f}"
def compute(e):
    D = "Biological_Physics/MethylPhys/doors/data/"
    if e["compute"] == "sam":
        R = rows(D + "DEV_SAM_LEVER_01/sam_01_mice.csv"); g = lambda k: [float(r["IAMA"]) for r in R if r["group"] == k]
        ko, wt, sa = g("knockout vehicle"), g("wild type"), g("knockout SAMe"); pr = e["prediction"]
        ratio = st.median(ko) / st.median(wt); p = mw_p_greater(ko, wt)
        return dict(nko=len(ko), nwt=len(wt), nsa=len(sa), ratio=ratio, p=p, same=st.median(sa) / st.median(wt), low=pr["low"], high=pr["high"],
                    inside=pr["low"] <= ratio <= pr["high"] and p < 0.05, commit=pr["sealed_commit"])
    if e["compute"] == "epiqc":
        R = [r for r in rows(D + "DEV_EPIQC_ARRAY_01/epiqc_array_01_rows.csv") if r["A"]]; by = {}
        for r in R: by.setdefault((r["line"], r["lab"]), []).append(float(r["A"]))
        rep = max(max(v) - min(v) for v in by.values() if len(v) > 1); nrep = sum(1 for v in by.values() if len(v) > 1)
        lines = {l for (l, _) in by}; three = [l for l in lines if len({lab for (ll, lab) in by if ll == l}) == 3]
        raw = max(max(st.mean(by[(l, lab)]) for lab in "ABC") - min(st.mean(by[(l, lab)]) for lab in "ABC") for l in three)
        T = rows(D + "DEV_EPIQC_ARRAY_01/epiqc_array_01_tared.csv"); tb = {}
        for r in T: tb.setdefault((r["line"], r["lab"]), []).append(float(r["A_rel"]))
        tared = max(max(st.mean(tb[(l, lab)]) for lab in "ABC") - min(st.mean(tb[(l, lab)]) for lab in "ABC") for l in three if all((l, lab) in tb for lab in "ABC"))
        return dict(arrays=len(R), lines=len(lines), labs=3, rep=rep, nrep=nrep, raw=raw, tared=tared, nthree=len(three))
    if e["compute"] == "fingerprint":
        F = D + "DEV_FINGERPRINT_01/"; R = rows(F + "fingerprint_01_rows.csv"); import math
        Hf = lambda x: -(x * math.log2(x) + (1 - x) * math.log2(1 - x)); S = {}
        for c in ("PrEC", "LNCaP"):
            rr = [r for r in R if r["cell"] == c]
            S[c] = dict(e=sum(float(r["errors"]) for r in rr) / sum(float(r["opportunities"]) for r in rr), m6=sum(float(r["m6"]) for r in rr),
                        rd=sum(float(r["read"]) for r in rr), ex=[float(r["excess_run_loss"]) for r in rr], n=len(rr))
        out = open(os.path.join(ROOT, F + "fingerprint_01_output.txt"), encoding="utf-8").read()
        MA = float(re.search(r"Met-A_rel ([\d.]+) on (\d+) sites", out).group(1)); nsites = int(re.search(r"on (\d+) sites", out).group(1))
        cB = float(re.search(r"curve B at IAM-A_rel ([\d.]+)", out).group(1)); z = float(re.search(r"z ([-\d.]+) ->", out).group(1))
        share = (S["LNCaP"]["rd"] / S["LNCaP"]["m6"]) / (S["PrEC"]["rd"] / S["PrEC"]["m6"]); IA = Hf(S["LNCaP"]["e"]) / Hf(S["PrEC"]["e"])
        armB = min(S["LNCaP"]["ex"]) > max(S["PrEC"]["ex"])
        return dict(IA=IA, share=share, MA=MA, nsites=nsites, cB=cB, z=z, exL=(min(S["LNCaP"]["ex"]), max(S["LNCaP"]["ex"])), exP=max(S["PrEC"]["ex"]),
                    nL=S["LNCaP"]["n"], nP=S["PrEC"]["n"], arm="B" if share < 0.70 else "A", inside=(armB if share < 0.70 else z > 1.645))
    if e["compute"] == "moss":
        R = rows(D + "DEV_CSCORE_MOSS_01/moss_mixes_01_rows.csv"); mix = [r for r in R if r["mix"].startswith("Mix")]
        leuk = [float(r["A"]) for r in R if r["mix"] == "unmixed leukocytes"]
        assert len(leuk) == 1, "the unmixed leukocyte array must be in the rows"; base = leuk[0]
        d = [abs(float(r["A"]) - base) for r in mix]   # sealed bar 1 (DEV_CSCORE_MOSS_01.md): A in Normal (0.95-1.05) and within 0.03 of the unmixed blood
        ok = sum(0.95 <= float(r["A"]) <= 1.05 and abs(float(r["A"]) - base) <= 0.03 for r in mix)
        return dict(n=len(mix), ok=ok, maxd=max(d), base=base, inside=ok == len(mix))
def tex_esc(s): return s.replace("_", r"\_").replace("%", r"\%").replace("&", r"\&")
def section(e, v):
    rec = tex_esc(e["record"].split("MethylPhys/")[-1])
    if e["compute"] == "sam":
        body = (r"Mat1a knockout mice cannot make S-adenosylmethionine (SAM) in the liver, so the methyl supply to the copier falls. "
                r"IAM's Law, through the restore rate of DNMT1, gives the rise in copy error; mapped through Stage~Q's measured response on one healthy "
                r"mouse's molecules, the window was committed (" + v["commit"] + r") before any knockout file was read. Liver RRBS, aligned reads, "
                + str(v["nwt"]) + r" healthy and " + str(v["nko"]) + r" knockout mice.")
        tab = [(r"sealed window, IAM-A knockout $\div$ healthy", f"{v['low']:.3f}--{v['high']:.3f}", r"\prediction"),
               (r"read, IAM-A knockout $\div$ healthy", f3(v["ratio"]), r"\measured"),
               (r"one-sided Mann--Whitney $p$, knockout above healthy", f"{v['p']:.4f}", r"\measured"),
               (r"knockout with SAMe restored $\div$ healthy", f3(v["same"]), r"\measured")]
        tail = r"The knockout livers also develop steatohepatitis, a second route downstream of the same SAM loss; this set does not separate the two."
    elif e["compute"] == "epiqc":
        body = (r"The same DNA of " + str(v["lines"]) + r" reference cell lines (SEQC2 EpiQC), run on EPIC v1 at three laboratories, "
                + str(v["arrays"]) + r" arrays, read by the chain unchanged. The cell lines are read on the neutrophil scale, so the readings test "
                r"reproducibility, not health.")
        tab = [(r"technical repeats, largest difference in $A$ (" + str(v["nrep"]) + r" repeat sets)", f"{v['rep']:.4f}", r"\measured"),
               (r"three laboratories, largest spread in $A$, before any tare (" + str(v["nthree"]) + r" lines)", f"{v['raw']:.4f}", r"\measured"),
               (r"three laboratories, largest spread after the same-run tare", f"{v['tared']:.4f}", r"\measured")]
        tail = ""
    elif e["compute"] == "fingerprint":
        body = (r"Prostate cancer cells (LNCaP) against normal prostate epithelium (PrEC), one laboratory, both instruments on the same cells: "
                + str(v["nL"]) + r" and " + str(v["nP"]) + r" sequencing runs, two EPIC arrays each. If cancer only made the copier worse, Met-A would sit on the line "
                r"the IAM-A $\leftrightarrow$ Met-A relation gives for the measured IAM-A; a fingerprint is Met-A above that line, or, where too few "
                r"molecules can be read for IAM-A, methylation lost in runs along molecules beyond every healthy run. Both arms and the choice between "
                r"them were committed before any cancer file was read, and the scorer was first shown to call a planted fingerprint and to stay silent on the line.")
        tab = [(r"IAM-A, cancer $\div$ normal", f3(v["IA"]), r"\measured"),
               (r"share of molecules IAM-A can read, cancer $\div$ normal (arm B decides below 0.70)", f3(v["share"]), r"\measured"),
               (r"excess run loss, every cancer run (largest normal run " + f"{v['exP']:.4f}" + r")", f"{v['exL'][0]:.4f}--{v['exL'][1]:.4f}", r"\measured"),
               (r"Met-A, cancer $\div$ normal, on " + f"{v['nsites']:,}" + r" prostate identity sites", f"{v['MA']:.4f}", r"\measured"),
               (r"the line at that IAM-A (arm A, recorded)", f"{v['cB']:.4f}", r"\calc"),
               (r"arm A, Met-A above the line, $z$", f"{v['z']:.2f}", r"\measured")]
        tail = (r"Both arms read a fingerprint: in these cancer cells blocks of the pattern were lost, beyond what copy error explains. One cell line against "
                r"one primary culture from one laboratory; LNCaP is a long-cultured line, so culture as well as cancer may contribute.")
    else:
        body = (r"One donor's blood DNA with 4--15~\% liver, lung, colon or neuron DNA mixed in at known fractions (Moss 2018), " + str(v["n"])
                + r" EPIC arrays. Foreign DNA at these fractions does not move the neutrophil identity sites, so Met-A must stay where the unmixed blood reads.")
        tab = [(r"sealed bar: Normal and within 0.03 of the unmixed blood", f"{v['ok']} of {v['n']}", r"\measured"),
               (r"largest shift in $A$", f"{v['maxd']:.4f}", r"\measured")]
        tail = ""
    t = "\n".join(f"{a} & {b} & {c} \\\\ \\rowrule" for a, b, c in tab)
    return (f"\\section{{{tex_esc(e['title'])}}}\n{body}\n\n\\begin{{center}}\\small\n\\begin{{tabular}}{{@{{}}p{{0.58\\linewidth}}p{{0.16\\linewidth}}p{{0.18\\linewidth}}@{{}}}}\n"
            f"\\toprule quantity & value & status \\\\\\midrule\n{t}\n\\end{{tabular}}\n\\end{{center}}\n"
            + (tail + "\n" if tail else "") + f"Record: \\path{{{e['record'].split('MethylPhys/')[-1]}}} ({e['date']}).\n")
def readme_row(e, v):
    rec = e["record"]; rel = os.path.relpath(os.path.join(ROOT, rec), os.path.join(ROOT, "Biological_Physics")); name = e.get("link_text") or os.path.basename(rec)
    links = f"[`{name}`]({rel})" + "".join(f", [`{os.path.basename(os.path.dirname(a)) if a.endswith('README.md') else os.path.basename(a)}`]({os.path.relpath(os.path.join(ROOT, a), os.path.join(ROOT, 'Biological_Physics'))})" for a in e.get("also", []))
    if e.get("compute") == "sam":
        h = (f"**IAM-A, first physics lever.** Cutting the liver's methyl supply (Mat1a knockout mice) raises copy error by the amount IAM's Law predicts: "
             f"window {v['low']:.3f}–{v['high']:.3f} sealed on a healthy mouse, knockout read {f3(v['ratio'])} against {v['nwt']} healthy mice (p = {v['p']:.4f}); "
             f"restoring SAMe moves it back ({f3(v['same'])}). The knockout livers also carry steatohepatitis, a second route not yet separated")
    elif e.get("compute") == "epiqc":
        h = (f"**Met-A reproduces across laboratories.** Identical DNA ({v['lines']} reference cell lines, SEQC2 EpiQC) reads the same at three laboratories "
             f"within {v['raw']*100:.1f} % before any tare; technical repeats within {v['rep']:.4f}")
    elif e.get("compute") == "fingerprint":
        h = (f"**Cancer fingerprint, both instruments on the same cells.** Prostate cancer (LNCaP) against normal prostate epithelium: methylation lost in runs on "
             f"every cancer run ({v['exL'][0]:.3f}–{v['exL'][1]:.3f} vs at most {v['exP']:.4f} in normal), and Met-A {v['MA']:.3f} above the line copy error allows "
             f"({v['cB']:.3f}); fingerprint by the rule sealed before reading. One line, one laboratory")
    elif e.get("compute") == "moss":
        h = f"**Met-A raises no false alarm** when 4–15 % liver, lung, colon or neuron DNA is mixed into blood DNA ({v['ok']} of {v['n']} within the sealed bar; largest shift {v['maxd']:.4f})"
    else: h = e["headline"]
    tag = {"development": " *(development)*", "withdrawn": " *(withdrawn)*"}.get(e["status"], "")
    return f"| {e['date']} | {h}{tag} | {links} |"
def build():
    R = json.load(open(os.path.join(HERE, "results_register.json"), encoding="utf-8"))["entries"]
    V = {e["id"]: (compute(e) if e.get("compute") else {}) for e in R}
    dev = [e for e in R if e["status"] == "development" and e.get("book")]
    tex = ("% GENERATED by CANON/results_to_tex.py from CANON/results_register.json. Do not edit by hand: change the register and rerun.\n"
           "\\chapter{Development results}\\label{ch:development}\n"
           "These results come from the instrument while it is in development. Each was tested against a prediction or a pass bar committed before its "
           "data were read, and each names its record in the repository. None of them is commissioned. A result leaves this chapter only when its "
           "scope is commissioned; the chapter is generated from the register of results, so it cannot fall behind the record.\n\n"
           + "\n".join(section(e, V[e["id"]]) for e in dev))
    rd = "\n".join(["| date | advancement | record |", "|---|---|---|"] + [readme_row(e, V[e["id"]]) for e in sorted(R, key=lambda x: x["date"], reverse=True) if e["status"] != "withdrawn"])
    return tex, rd, R, V
def main():
    tex, rd, R, V = build(); open(TEX, "w", encoding="utf-8").write(tex)
    s = open(README, encoding="utf-8").read(); i, j = s.index(B), s.index(E)
    open(README, "w", encoding="utf-8").write(s[:i + len(B)] + "\n" + rd + "\n" + s[j:]); print("wrote", os.path.relpath(TEX, ROOT), "and the README Advancements table")
    for e in R:
        if e.get("compute"): print(" ", e["id"], {k: (round(v, 4) if isinstance(v, float) else v) for k, v in V[e["id"]].items()})
if __name__ == "__main__": main()
