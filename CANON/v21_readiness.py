"""Atlas v2.1 readiness: computes every item's state from the repository (files present, stated checks pass) and writes
Biological_Physics/MethylPhys/V21_READINESS.md. Nothing is ticked by hand.
  python3 CANON/v21_readiness.py           write the board
  python3 CANON/v21_readiness.py --check   refuse if the board differs from the repository, or a manifest id is unknown (status_check)
  python3 CANON/v21_readiness.py --launch  refuse unless every before_launch item is met (run_v21.sh calls this first)
"""
import json, os, sys, hashlib
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "Biological_Physics", "MethylPhys", "V21_READINESS.md")
def state(x):
    miss = [f for f in x["files"] if not os.path.exists(os.path.join(ROOT, f))]
    if miss: return False, "missing: " + ", ".join(os.path.basename(f) for f in miss)
    for f, word in x["checks"].get("contains", []):
        if word not in open(os.path.join(ROOT, f), encoding="utf-8", errors="replace").read(): return False, f"{os.path.basename(f)} does not say {word}"
    for f in x["checks"].get("sha_of", []):
        J = json.load(open(os.path.join(ROOT, f), encoding="utf-8"))
        for g, h in J.get("sha256", {}).items():
            p = os.path.join(ROOT, g)
            if not os.path.exists(p) or hashlib.sha256(open(p, "rb").read()).hexdigest() != h: return False, f"sealed checksum no longer matches {os.path.basename(g)}"
    return True, "met"
def render(J):
    L = ["# Atlas v2.1 readiness", "", "Generated by `CANON/v21_readiness.py` from `CANON/v21_readiness.json`; never edited by hand. An item is met only",
         "when its files are in the repository and their checks pass. The box run refuses to start until every *before launch* item is met.", ""]
    names = {"before_launch": "Before launch (the run refuses to start without these)", "box_first": "On the box, before the full fit", "after_fit": "After the fit: the gift package"}
    for st in ("before_launch", "box_first", "after_fit"):
        xs = [x for x in J["items"] if x["stage"] == st]; met = sum(state(x)[0] for x in xs)
        L += [f"## {names[st]}: {met} of {len(xs)} met", "", "| # | Item | State | Proof (files) | Manifest |", "|---|---|---|---|---|"]
        for x in xs:
            ok, why = state(x)
            L.append(f"| {x['id']} | {x['what']} | {'MET' if ok else 'open - ' + why} | " + ", ".join(f"`{os.path.basename(f)}`" for f in x["files"]) + f" | {', '.join(x['manifest'])} |")
        L.append("")
    return "\n".join(L) + "\n"
if __name__ == "__main__":
    J = json.load(open(os.path.join(ROOT, "CANON", "v21_readiness.json"), encoding="utf-8"))
    if "--launch" in sys.argv:
        open_ = [f"{x['id']} {state(x)[1]}" for x in J["items"] if x["stage"] == "before_launch" and not state(x)[0]]
        print("v21_readiness: " + ("LAUNCH ALLOWED" if not open_ else "LAUNCH REFUSED: " + "; ".join(open_))); sys.exit(1 if open_ else 0)
    M = {r["id"] for r in json.load(open(os.path.join(ROOT, "CANON", "manifest.json"), encoding="utf-8"))["rows"]}
    bad = sorted({m for x in J["items"] for m in x["manifest"] if m not in M})
    if "--check" in sys.argv:
        P = ([f"unknown manifest ids: {bad}"] if bad else []) + (["V21_READINESS.md differs from the repository (run python3 CANON/v21_readiness.py)"] if not os.path.exists(OUT) or open(OUT, encoding="utf-8").read() != render(J) else [])
        print("v21_readiness: " + ("ok" if not P else "REFUSED: " + "; ".join(P))); sys.exit(1 if P else 0)
    open(OUT, "w", encoding="utf-8").write(render(J)); print("v21_readiness: written")
