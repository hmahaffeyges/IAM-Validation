#!/usr/bin/env python3
"""CANON/report_text.py - writes the report's explanations from the one source, CANON/catalogue.json ("report"), into the chain
(Biological_Physics/MethylPhys/chain/Runtime Matrices/Report/report_text.json), so a copy of the chain folder alone carries them (2026-10-23;
author: 'populated via code from the same database'). Each section's status line is the catalogue instrument's commissioned scope, with its date
removed (no dates in prose); a section with no instrument is development. Usage: python3 CANON/report_text.py [--check]"""
import json, os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "Biological_Physics", "MethylPhys", "chain", "Runtime Matrices", "Report", "report_text.json")
def build():
    C = json.load(open(os.path.join(ROOT, "CANON", "catalogue.json"), encoding="utf-8")); R = C["report"]; I = {i["id"]: i for i in C["instruments"]}
    S = {}
    for k, v in R["sections"].items():
        x = {a: b for a, b in v.items() if a != "instrument"}; i = I.get(v.get("instrument"))
        c = str(i.get("commissioned") or "") if i else ""
        c = re.sub(r",?\s*\d{4}-\d{2}-\d{2}", "", c).strip(" ,")
        c = re.sub(r"^(tested and )?commissioned (on|for) ", "", c, flags=re.I)
        x["status"] = ("Commissioned on " + c + "." if c else "Commissioned.") if i else \
                      "Development: produced by the same chain and shown for examination; not yet commissioned, so not a finding."
        x.pop("status_extra", None)
        if v.get("status_extra"): x["status"] += " " + v["status_extra"]
        x["instrument_name"] = i["name"] if i else None; S[k] = x
    return {"_source": "generated by CANON/report_text.py from CANON/catalogue.json (report); do not edit", "intro": R["intro"], "sections": S}
if __name__ == "__main__":
    new = json.dumps(build(), indent=1, ensure_ascii=False) + "\n"
    old = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
    if "--check" in sys.argv:
        print("report_text: " + ("ok" if old == new else "DIFFERS from CANON/catalogue.json; run python3 CANON/report_text.py")); sys.exit(0 if old == new else 1)
    os.makedirs(os.path.dirname(OUT), exist_ok=True); open(OUT, "w", encoding="utf-8").write(new); print("report_text: wrote " + os.path.relpath(OUT, ROOT))
