"""Which files in the chain are LIVE on the commissioned path, which are tools, and which are class-era leftovers.

Why: 12 of the 23 files in Biological_Physics/MethylPhys/chain/ are not reachable from the commissioned entry points, and some
of those are from the retired class gauge (per-class means, per-class surface brightness). A reader - or a future session -
could mistake them for live code. This script computes the LIVE set by walking imports from the entry points, prints it beside
a committed classification, and refuses when the two disagree: a file that becomes live, or stops being live, must be declared.

Classification (CLASSES below) is deliberate, not computed:
  live       reached from an entry point; part of a reading
  tool       a separate utility or build/release script, not part of a reading
  class_era  from the RETIRED class gauge (CANON/foundation.json, retired_foundations); never to be used or cited

Usage: python3 CANON/chain_manifest.py [--write]
"""
import ast, json, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CH = os.path.join(ROOT, "Biological_Physics/MethylPhys/chain")
ENTRY = ["conductor_v3", "stage_v4", "stage_1_idat_calibration", "stage_q_iam_a", "stage_q0_intake", "stage_q2_selfref", "stage_atlas_commission", "stage_atlas_u1", "stage_atlas_u1_planted", "stage_atlas_u2", "stage_atlas_u3", "stage_deconv_v21"]
CLASSES = {
 "build_all": "tool", "build_chain_sequence": "tool", "release_check_v3": "tool", "release_check_v4": "tool", "serial_mode": "tool",
 "pat_eps_fast": "tool", "cmb_tools": "tool", "toolkit_foreign_detection": "tool", "stage_a_composition_v2": "tool",
 "nilc_celltype_deconvolver": "class_era", "stage_2c_trace_detection": "class_era",
 "stage_4_6_patient_cmb": "class_era", "toolkit_surface_brightness": "class_era",
}
MANIFEST = os.path.join(CH, "CHAIN_MANIFEST.md")

def live_set():
    mods = {f[:-3] for f in os.listdir(CH) if f.endswith(".py")}
    live, stack = set(), list(ENTRY)
    while stack:
        m = stack.pop()
        if m in live or m not in mods: continue
        live.add(m)
        t = ast.parse(open(os.path.join(CH, m + ".py"), encoding="utf-8").read())
        for n in ast.walk(t):
            if isinstance(n, ast.Import): stack += [a.name.split(".")[0] for a in n.names]
            elif isinstance(n, ast.ImportFrom) and n.module: stack.append(n.module.split(".")[0])
    return live, mods

def table():
    live, mods = live_set()
    L = ["# What each file in the chain is (generated by `CANON/chain_manifest.py --write`; do not edit by hand)", "",
         "The LIVE column is computed by walking imports from the commissioned entry points "
         f"({', '.join(ENTRY)}). The kind is declared in the script and checked against it.", "",
         "| file | reached from an entry point | kind |", "|---|---|---|"]
    for m in sorted(mods):
        kind = "live" if m in live else CLASSES.get(m, "UNDECLARED")
        L.append(f"| `{m}.py` | {'yes' if m in live else 'no'} | {kind} |")
    L += ["", "**class_era** files are from the retired class gauge (eight per-class floors fitted by MCMC; "
          "`CANON/foundation.json`, `retired_foundations`). They are not used by any reading and must never be cited. "
          "They are kept so the history stays readable, not because anything depends on them.", ""]
    return "\n".join(L)

def problems():
    live, mods = live_set(); P = []
    for m in sorted(mods - live):
        if m not in CLASSES: P.append(f"chain/{m}.py is not reached from an entry point and is not declared in CANON/chain_manifest.py")
    for m, k in CLASSES.items():
        if m in live: P.append(f"chain/{m}.py is declared '{k}' but IS reached from an entry point - declare it live or remove the import")
        elif not os.path.isfile(os.path.join(CH, m + ".py")): P.append(f"chain/{m}.py is declared '{k}' but the file is gone")
    if not os.path.isfile(MANIFEST) or open(MANIFEST, encoding="utf-8").read().strip() != table().strip():
        P.append("chain/CHAIN_MANIFEST.md differs from the computed table: run python3 CANON/chain_manifest.py --write")
    return P

if __name__ == "__main__":
    if "--write" in sys.argv:
        open(MANIFEST, "w", encoding="utf-8").write(table() + "\n"); print("chain_manifest: wrote chain/CHAIN_MANIFEST.md"); sys.exit(0)
    P = problems()
    print("chain_manifest: " + ("ok (" + str(len(live_set()[0])) + " live, " + str(sum(1 for v in CLASSES.values() if v == 'class_era')) + " class-era)" if not P else "REFUSED:\n  " + "\n  ".join(P)))
    sys.exit(1 if P else 0)
