#!/usr/bin/env python3
"""Status sentences, generated (author 2026-10-16: one source per fact). Writes one sentence between <!-- STATUS:BEGIN --> and
<!-- STATUS:END --> in every file listed in FILES, from CANON/commissioning.json (what is commissioned) and CANON/catalogue.json with the
manifest (the atlas's stage). Usage: python3 CANON/status_lines.py [--check]"""
import os, sys, json, re
H = os.path.dirname(os.path.abspath(__file__)); R = os.path.dirname(H); sys.path.insert(0, H); import catalogue as CAT
FILES = ["Biological_Physics/MethylPhys/README.md", "Biological_Physics/README.md", "REFERENCE.md"]
J = lambda p: json.load(open(os.path.join(R, p), encoding="utf-8"))
C = J("CANON/commissioning.json"); K = {i["id"]: i for i in J("CANON/catalogue.json")["instruments"]}; M = {r["id"]: r for r in J("CANON/manifest.json")["rows"]}
def sentence(f):
    d = os.path.dirname(os.path.join(R, f)); rel = lambda p: os.path.relpath(os.path.join(R, p), d)
    com = "; ".join(f"{i['summary']} ([note]({rel('Biological_Physics/MethylPhys/doors/' + os.path.basename(i['note']))}))" if i.get("note") else i["summary"] for i in C["instruments"] if i.get("summary"))
    at = CAT.stage(K["atlas"], M)
    return (f"**Status (generated by `CANON/status_lines.py`):** commissioned: {com}. Everything else is in development; not a diagnostic test. "
            f"IAM-Atlas v2 is the reference in use; v2.1 is {at}. Every instrument and its next step: [INSTRUMENTS.md]({rel('INSTRUMENTS.md')}); "
            f"what is commissioned and the recent results: [STATUS.md]({rel('Biological_Physics/MethylPhys/STATUS.md')}).")
B, E = "<!-- STATUS:BEGIN -->", "<!-- STATUS:END -->"
bad = []
for f in FILES:
    p = os.path.join(R, f); s = open(p, encoding="utf-8").read()
    if B not in s: bad.append(f"{f}: no STATUS markers"); continue
    n = re.sub(re.escape(B) + r".*?" + re.escape(E), B + "\n" + sentence(f) + "\n" + E, s, flags=re.S)
    if "--check" in sys.argv:
        if n != s: bad.append(f"{f}: status sentence differs (run python3 CANON/status_lines.py)")
    else: open(p, "w", encoding="utf-8").write(n)
print("status_lines: " + ("ok" if not bad else "REFUSED: " + "; ".join(bad))); sys.exit(1 if bad else 0)
