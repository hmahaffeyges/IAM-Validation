"""One-line pointer left where a consolidated document used to live (author 2026-10-16: fewer documents to keep updated; no link breaks)."""
import os
def text(here, target, what):
    rel = os.path.relpath(target, os.path.dirname(here))
    return f"# Moved\n\n{what} now lives in [{os.path.basename(target)}]({rel}), generated by code. This file is kept only so older links still work (consolidated 2026-10-16).\n"
def write(root, here, target, what):
    p = os.path.join(root, here); open(p, "w", encoding="utf-8").write(text(p, os.path.join(root, target), what))
