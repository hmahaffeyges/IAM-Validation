"""Atlas v2.1 release checklist: every deliverable checked in each place it must be. Usage:
  python3 CANON/v21_release.py --verify    (needs AWS) checks the repo and S3, writes CANON/v21_release_verified.json and the checklist
  python3 CANON/v21_release.py --zenodo FILE_LIST.json   ticks Zenodo boxes from the deposit's own file list (after upload)
  python3 CANON/v21_release.py             rewrites V21_RELEASE_CHECKLIST.md from the last verification (no network)
  python3 CANON/v21_release.py --check     status_check: the checklist matches the register and the last verification
  python3 CANON/v21_release.py --ready     the Zenodo uploader calls this first; exit 1 while any required box is open
"""
import os, sys, json, subprocess, time
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); BUCKET = "methylphys-data-945451304272-us-west-2-an"
REG = os.path.join(ROOT, "CANON", "v21_release.json"); VER = os.path.join(ROOT, "CANON", "v21_release_verified.json")
OUT = os.path.join(ROOT, "Biological_Physics", "MethylPhys", "V21_RELEASE_CHECKLIST.md")
def tracked(p):
    return subprocess.run(["git", "ls-files", "--error-unmatch", p], cwd=ROOT, capture_output=True).returncode == 0
def verify():
    import boto3; s3 = boto3.client("s3"); V = json.load(open(VER)) if os.path.exists(VER) else {}
    for x in json.load(open(REG))["items"]:
        repo = {p: tracked(p) for p in x["repo"]}
        s3m = {}
        for k in x["s3"]:
            if k.endswith("/"): s3m[k] = s3.list_objects_v2(Bucket=BUCKET, Prefix=k, MaxKeys=1)["KeyCount"] > 0
            else:
                try: s3.head_object(Bucket=BUCKET, Key=k); s3m[k] = True
                except Exception: s3m[k] = False
        V[x["id"]] = dict(repo=repo, s3=s3m, zenodo=V.get(x["id"], {}).get("zenodo"), verified_utc=time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()))
    json.dump(V, open(VER, "w"), indent=1); open(VER, "a").write("\n")
def boxes(x, v):
    r = "n/a" if not x["repo"] else ("yes" if v and all(v["repo"].get(p) for p in x["repo"]) else "no")
    s = "n/a" if not x["s3"] else ("yes" if v and all(v["s3"].get(k) for k in x["s3"]) else "no")
    z = "n/a" if not x["zenodo"] else ("yes" if v and v.get("zenodo") else "no")
    return r, s, z
def render():
    R = json.load(open(REG)); V = json.load(open(VER)) if os.path.exists(VER) else {}
    ic = {"yes": "[x]", "no": "[ ]", "n/a": "-"}
    L = ["# Atlas v2.1 release checklist", "", "Generated by `CANON/v21_release.py` from `CANON/v21_release.json` and the last verification; never edited by hand.",
         "A box is ticked only when code finds the file there. The Zenodo upload refuses while any required box is open.", ""]
    tot = req_open = 0
    need = done = 0
    for g in dict.fromkeys(x["track"] for x in R["items"]):   # one ordered list (author 2026-10-16): tracks A-D needed for the gift, then after the gift
        L += [f"## {g}", "", "| Step | # | Deliverable | Needed for the gift | Repo | S3 | Zenodo |", "|---|---|---|---|---|---|---|"]
        for x in sorted([x for x in R["items"] if x["track"] == g], key=lambda x: x["step"]):
            b = boxes(x, V.get(x["id"])); tot += 1
            if x["required"]:
                need += 1; done += "no" not in b
                if "no" in b: req_open += 1
            L.append(f"| {x['step']} | {x['id']} | {x['what']} | {'yes' if x['required'] else 'no'} | {ic[b[0]]} | {ic[b[1]]} | {ic[b[2]]} |")
        L.append("")
    L.insert(5, f"**{done} of {need} items needed for the gift complete; {tot - need} items after the gift.**  "
                f"Last verified: {max((v.get('verified_utc', '') for v in V.values()), default='never')}.\n")
    return "\n".join(L) + "\n", req_open
if __name__ == "__main__":
    a = sys.argv[1:]
    if "--verify" in a: verify()
    if "--zenodo" in a:
        files = set(json.load(open(a[a.index("--zenodo") + 1])))
        V = json.load(open(VER))
        for x in json.load(open(REG))["items"]:
            if x["zenodo"]: V.setdefault(x["id"], {})["zenodo"] = any(f == x["zenodo"] or (x["zenodo"].endswith("/") and f.startswith(x["zenodo"])) for f in files)
        json.dump(V, open(VER, "w"), indent=1); open(VER, "a").write("\n")
    txt, n_open = render()
    if "--check" in a:
        ok = os.path.exists(OUT) and open(OUT, encoding="utf-8").read() == txt
        print("v21_release: " + ("ok" if ok else "REFUSED: V21_RELEASE_CHECKLIST.md differs (run python3 CANON/v21_release.py)")); sys.exit(0 if ok else 1)
    if "--ready" in a:
        print(f"v21_release: {'READY' if n_open == 0 else f'NOT READY, {n_open} required items open'}"); sys.exit(0 if n_open == 0 else 1)
    open(OUT, "w", encoding="utf-8").write(txt); print(f"v21_release: written ({n_open} required items open)")
