"""The book's toolbox chapter (author 2026-10-15: a chapter that explains every tool in the toolbox, commissioned, in development or a
candidate; not a real-time report). Generated from CANON/catalogue.json (instruments and support tools; stage computed by catalogue.py from
the manifest) and CANON/instruments.json (candidates). Writes docs/book/part6/p6_06b_toolbox.tex. --check refuses drift."""
import sys as _sud, os as _oud; _sud.path.insert(0, _oud.path.join(_oud.path.dirname(_oud.path.dirname(_oud.path.abspath(__file__))), 'CANON')) if _oud.path.basename(_oud.path.dirname(_oud.path.abspath(__file__))) != 'CANON' else _sud.path.insert(0, _oud.path.dirname(_oud.path.abspath(__file__))); from undate import undate as _undate   # no dates in public prose (plan 39.15)
import os, sys, json, re, importlib.util
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
OUT = os.path.join(ROOT, "docs", "book", "part6", "p6_06b_toolbox.tex")
_s = importlib.util.spec_from_file_location("cat", os.path.join(ROOT, "CANON", "catalogue.py")); CAT = importlib.util.module_from_spec(_s); _s.loader.exec_module(CAT)
def tex(t):
    t = str(t)
    for a, b in (("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"), ("$", r"\$"), ("#", r"\#"), ("_", r"\_"), ("{", r"\{"), ("}", r"\}"), ("~", r"\textasciitilde{}"), ("^", r"\^{}")):
        t = t.replace(a, b)
    return t.replace("≥", r"$\geq$").replace("≤", r"$\leq$").replace("−", "-").replace("×", r"$\times$")
KEEP = {"WCGW", "CMB", "EPIC", "DNA", "ATP", "RRBS", "WGBS"}
def calm(t):
    """the candidate board writes emphasis in capitals; the book does not"""
    return re.sub(r"\b([A-Z][A-Z-]{2,})\b", lambda m: m.group(1) if m.group(1) in KEEP else m.group(1).lower(), str(t))
def stage_word(i, M):
    return ("Commissioned (" + i["commissioned"] + ")") if i.get("commissioned") else "In development"
def build():
    C, M = CAT.load(); J = json.load(open(os.path.join(ROOT, "CANON", "instruments.json"), encoding="utf-8"))
    L = [r"% GENERATED by CANON/book_toolbox.py from CANON/catalogue.json and CANON/instruments.json. Do not edit by hand.",
         r"\chapter{The toolbox}\label{ch:toolbox}", "",
         "Every reading in this part comes from one of a small set of tools. Each answers its own question and has its own specialty; "
         "together they look at a sample from different sides, so that what one cannot see another can. This chapter introduces each "
         "tool and says where it stands: \\emph{commissioned} (it passed every test written for it before its data were read, and its "
         "readings in that scope are results), \\emph{in development}, or a \\emph{candidate} still being designed. The chapters that "
         "follow give the physics and the evidence.", "", r"\section{The instruments}", ""]
    for i in C["instruments"]:
        ref = f" (Chapter~\\ref{{{i['book_chapter']}}})" if i.get("book_chapter") else ""
        L += [f"\\subsection*{{{tex(i['name'])}}}", f"\\textbf{{The question.}} {tex(i['question'])}\\par",
              f"\\textbf{{How it reads.}} {tex(i['how'])}\\par", f"\\textbf{{Its specialty.}} {tex(i['specialty'])}{ref}\\par",
              f"\\textbf{{Reads from.}} {tex(i['reads'])}. \\textbf{{Status.}} {tex(stage_word(i, M))}.\\par", ""]
    L += [r"\section{The tools the instruments run on}", "", r"\begin{itemize}"]
    for t in C["support_tools"]: L.append(f"\\item \\textbf{{{tex(t['name'])}.}} {tex(t['what'])} (Chapter~\\ref{{{t['chapter']}}})")
    L += [r"\end{itemize}", "", r"\section{Candidates}", "",
          "Readings still being designed, each with what it would add and what it cannot see. A candidate becomes an instrument only by "
          "passing tests written before its data are read.", "", r"\begin{itemize}"]
    for c in J["instruments"]:
        if str(c.get("status", "")).startswith("DONE"): continue
        nm = tex(re.sub(r":.*$", "", c["name"])); rd = tex(calm(c["reads"])); ad = tex(calm(c["advantage"])); bl = tex(calm(c["blind"]))
        L.append("\\item \\textbf{" + nm + ".} \\emph{What it reads:} " + rd + " \\emph{What it adds:} " + ad + " \\emph{What it cannot see:} " + bl)
    L += [r"\end{itemize}", "", r"\section{Why several}", "", tex(C["together"]) if isinstance(C.get("together"), str) else tex(" ".join(C.get("together", []))) , ""]
    return "\n".join(L) + "\n"
if __name__ == "__main__":
    t = _undate(build())
    if "--check" in sys.argv:
        ok = os.path.exists(OUT) and open(OUT, encoding="utf-8").read() == t
        print("book_toolbox: " + ("ok" if ok else "REFUSED: docs/book/part6/p6_06b_toolbox.tex differs (run python3 CANON/book_toolbox.py)")); sys.exit(0 if ok else 1)
    open(OUT, "w", encoding="utf-8").write(t); print("book_toolbox: wrote docs/book/part6/p6_06b_toolbox.tex")
