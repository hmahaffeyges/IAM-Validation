#!/usr/bin/env python3
"""CANON/four_domains.json -> FOUR_DOMAINS.md: the four-domain schematic and its gap map (author, 2026-10-14).
--check: refuse a slot missing a domain, an unknown status, or a FOUR_DOMAINS.md that differs from what this script writes."""
import sys as _sud, os as _oud; _sud.path.insert(0, _oud.path.join(_oud.path.dirname(_oud.path.dirname(_oud.path.abspath(__file__))), 'CANON')) if _oud.path.basename(_oud.path.dirname(_oud.path.abspath(__file__))) != 'CANON' else _sud.path.insert(0, _oud.path.dirname(_oud.path.abspath(__file__))); from undate import undate as _undate   # no dates in public prose (plan 39.15)
import json, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
J = json.load(open(os.path.join(ROOT, "CANON", "four_domains.json"), encoding="utf-8"))
OUT = os.path.join(ROOT, "FOUR_DOMAINS.md")
OK = {"derived", "measured", "calculated", "definition", "prediction", "conjecture", "interp", "candidate", "open"}
HAVE = {"derived", "measured", "calculated", "definition"}
D = J["domains"]; P = []
for s in J["slots"]:
    for d in D:
        if d not in s: P.append(f"slot {s['id']}: no entry for {d}")
        elif s[d]["status"] not in OK: P.append(f"slot {s['id']} {d}: unknown status {s[d]['status']!r}")
def cell(e): return f"{e['formula']} *({e['status']})*" + (f" — {e['native']}" if e["native"] not in ("none", "not defined in the book", "not in the book") else "")
L = ["# The four-domain schematic", "", "Generated by `CANON/four_domains.py` from `CANON/four_domains.json`; do not edit by hand.",
     J.get("preamble", ""), "",
     *((lambda k: [f"## {k['title']}", "", k["intro"], "", "| IAM | A computer's memory | Value for the cell |", "|---|---|---|"]
        + [f"| {r[0]} | {r[1]} | {r[2]} |" for r in k["rows"]] + ["", "And for a qubit:", ""] + [f"- {x}" for x in k["qubit"]] + ["", k["closing"], ""])(J["plain_key"])
       if J.get("plain_key") else []),
     "One standard name per slot; each domain's own word for it follows the formula. Status: derived, measured, calculated, prediction,",
     "definition, conjecture, interp (the book's interpretation), candidate (proposed, not tested), open (nothing yet).", "The book is the source; every entry cites a book section or App. E number.", "",
     "| Standard name | " + " | ".join(x.capitalize() for x in D) + " |", "|---|" + "---|" * len(D)]
for s in J["slots"]: L.append(f"| **{s['name']}**<br>{s['definition']} | " + " | ".join(cell(s[d]) for d in D) + " |")
L += ["", "## Score", "", "| Domain | derived, measured, calculated or definition | conjecture, interpretation or candidate | open |", "|---|---|---|---|"]
for d in D:
    st = [s[d]["status"] for s in J["slots"]]
    L.append(f"| {d.capitalize()} | {sum(x in HAVE for x in st)} of {len(st)} | {sum(x in ('conjecture','interp','candidate','prediction') for x in st)} | {st.count('open')} |")
L += ["", "## Gap map: what each domain is missing, and who already has it", ""]
for d in D:
    gaps = [s for s in J["slots"] if s[d]["status"] not in HAVE]
    L.append(f"**{d.capitalize()}** ({len(gaps)} gaps)")
    for s in gaps:
        donors = [x for x in D if x != d and s[x]["status"] in HAVE]
        L.append(f"- {s['name']}: {s[d]['status']}" + (f"; donor: {', '.join(donors)}" if donors else "; no domain has it yet"))
    L.append("")
MX = [(s["name"], d, s[d]["status"], s[d]["mixed_tags"]) for s in J["slots"] for d in D if s[d].get("mixed_tags")]
if MX:
    L += ["## Boxes with mixed tags in the book (weakest shown; confirm by hand)", ""] + [f"- {n}, {d}: shown as {st}; the book tags it {', '.join(t)}" for n, d, st, t in MX] + [""]
txt = "\n".join(L) + "\n"
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__))); import bit_tables as _BT; txt = txt.rstrip("\n") + "\n\n" + _BT.render()   # IAM in bits, merged 2026-10-16
txt = _undate(txt)
if "--check" in sys.argv:
    if not os.path.exists(OUT) or open(OUT, encoding="utf-8").read() != txt: P.append("FOUR_DOMAINS.md differs (run python3 CANON/four_domains.py)")
    print("four_domains: " + ("REFUSED\n  " + "\n  ".join(P) if P else f"ok ({len(J['slots'])} slots)")); sys.exit(1 if P else 0)
if P: print("four_domains: REFUSED\n  " + "\n  ".join(P)); sys.exit(1)
open(OUT, "w", encoding="utf-8").write(txt); print(f"four_domains: written ({len(J['slots'])} slots)")
