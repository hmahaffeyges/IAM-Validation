"""Shift turnover: one day log per day, written at the end of the day from CANON/daylogs/<date>.json.

Why this exists (author, 2026-10-13): the work moves faster than a live page can track, and trying to keep everything current in
real time is what makes a running log fragile. A control-room turnover is written once, at a fixed time, by whoever was on shift.
A day log is for a researcher or a donor reading months later. The section names are fixed so one day can be compared with another:
what we set out to do; what ran and how each came out; what we learned that we did not know yesterday; our own mistakes and what caught
each; "Coffee and a whiteboard" - the back-and-forth that produced the day's work, bad ideas included (the author's name for it, and the
part a potential collaborator is actually evaluating); what changed in the plan; and what is open at turnover.

Filtering rules, enforced here rather than remembered:
 1. every result entry carries a STATUS from a fixed vocabulary, so nothing unsealed can be written as though it were established;
 2. every record a log names must exist in the repository;
 3. no hype word anywhere in a day log (the front page's own list, CANON/now_running.HYPE);
 4. the voice is "we", as on the page - first person singular is refused outside a quoted question from the author.

Usage: python3 CANON/daylog.py [--check]
Writes Biological_Physics/MethylPhys/daylogs/<date>.md for each day and daylogs/README.md as the index.
"""
import glob, json, os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
SRC = os.path.join(HERE, "daylogs"); OUT = os.path.join(ROOT, "Biological_Physics", "MethylPhys", "daylogs")
STATUS = {"sealed", "development", "synthetic only", "audit", "failed", "diagnosis", "in progress", "metadata only", "structure"}
sys.path.insert(0, HERE)
import now_running as NR
FIRST = re.compile(r"(?<![\w'])(I|I'm|I'd|I've|my|mine)(?![\w'])")

def one(d, path):
    P = []
    for k in ("date", "title", "set_out", "sections", "open_at_turnover"):
        if not d.get(k): P.append(f"[daylog] {os.path.basename(path)}: no {k}")
    blob = json.dumps(d)
    h = NR.HYPE.search(blob)
    if h: P.append(f"[daylog] {os.path.basename(path)}: hype word '{h.group(0)}'")
    if d.get("check_completeness"): P += completeness(d)
    for sec in d.get("sections", []):
        for e in sec.get("entries", []):
            if sec.get("kind") in ("win", "loss", "ran") and e.get("status") not in STATUS:
                P.append(f"[daylog] {d.get('date')}: entry '{str(e.get('what'))[:40]}' has status "
                         f"{e.get('status')!r}, not one of {sorted(STATUS)}")
            r = e.get("record")
            if r and not os.path.isfile(os.path.join(ROOT, r)): P.append(f"[daylog] {d.get('date')}: record {r} does not exist")
            for t in (e.get("what", ""), e.get("why", "")):
                m = FIRST.search(t)
                if m: P.append(f"[daylog] {d.get('date')}: first person '{m.group(0)}' outside a quoted question")
    return P

def render(d):
    L = [f"# {d['date']} — {d['title']}", "",
         "_Shift turnover. Written at the end of the day, from `CANON/daylogs/" + d["date"] + ".json`; generated by "
         "`CANON/daylog.py`, so it cannot drift from its source. Filtered for a reader, not a transcript._", "",
         "## What we set out to do", "", d["set_out"], ""]
    for sec in d["sections"]:
        L += [f"## {sec['heading']}", ""]
        if sec.get("lead"): L += [sec["lead"], ""]
        if sec.get("table"):
            t = sec["table"]
            L += ["| " + " | ".join(t["columns"]) + " |", "|" + "---|" * len(t["columns"])]
            for r in t["rows"]: L.append("| " + " | ".join(str(x) for x in r) + " |")
            L.append("")
        for e in sec.get("entries", []):
            head = f"**{e['title']}**" + (f" — _{e['status']}_" if e.get("status") else "")
            L.append(f"- {head}  ")
            L.append(f"  {e['what']}  ")
            if e.get("why"): L.append(f"  _Why it matters:_ {e['why']}  ")
            if e.get("record"): L.append(f"  [the record]({os.path.relpath(os.path.join(ROOT, e['record']), OUT)})")
        L.append("")
    c = d.get("compute")
    if c:   # CANON/day_compute.py, from AWS billing (author 2026-10-19: show day to day the work put in and the money spent)
        cats = ", ".join(f"{k} ${v:,.2f}" for k, v in c.get("by_category", {}).items())
        L += ["## Computing and cost", "",
              f"This day: **${c['billed_usd']:,.2f}** billed by AWS ({cats}); {c['machine_hours']:,} machine hours, {c['core_hours']:,} processor-core hours.  ",
              f"Since {c['since']}: **${c['total_billed_usd']:,.2f}**; {c['total_machine_hours']:,} machine hours, {c['total_core_hours']:,} processor-core hours.  ",
              f"_{c['source']}; " + ("final._" if c.get("final") else f"read {c['read']}, AWS bills about a day behind, so it is updated until final._"), ""]
    L += ["## Open at turnover", "", d["open_at_turnover"], ""]
    if d.get("corrected"): L += ["## Corrected", "", d["corrected"], ""]   # a later audit of this day log, dated (author 2026-10-19)
    if d.get("closing"): L += ["---", "", f"_{d['closing']}_", ""]
    return "\n".join(L)

STOP = set("the a an and or of for in on at to is was with by from that this it its as not no into our we us "
               "day push rule author before after every each one two three now still open".split())

def completeness(d):
    """Every lever in CANON/levers.json and every instrument in CANON/instruments.json must appear in the day log.

    The author's requirement: nothing forgotten. A day log that leaves one out is refused rather than trusted.
    """
    out, txt = [], render(d)
    for f, key, label in (("levers.json", "levers", "lever"), ("instruments.json", "instruments", "instrument")):
        fp = os.path.join(HERE, f)
        if not os.path.isfile(fp): continue
        for x in json.load(open(fp, encoding="utf-8"))[key]:
            name = x.get("name") or x.get("id") or ""
            short = name.split(":")[0].split("(")[0].strip()
            if short and short.lower() not in txt.lower() and (x.get("id", "").lower() not in txt.lower()):
                out.append(f"[daylog] {d['date']}: {label} '{short}' has no row in the day log")
    return out

def page_lists_every_day(days):
    """The front page's day-log section must list every generated day log, so a day cannot exist and be invisible."""
    b = os.path.join(ROOT, "website", "build", "build_home.py")
    if not os.path.isfile(b) or "id=\"daylogs\"" not in open(b, encoding="utf-8").read(): return []
    # the section is generated from the daylogs directory itself, so the only failure mode is a day log that was never rendered
    return [f"[daylog] {d['date']}: no rendered day log for the page to list"
            for d in days if not os.path.isfile(os.path.join(OUT, d["date"] + ".md"))]

def pacific_heads():
    """Every development-log heading with the PACIFIC day it was committed (git blame author time; uncommitted lines: today).
    The author works on Pacific time; headings were for a while dated by UTC, so a day log is checked against when a thread was
    actually committed, not the date written in its heading (2026-10-14 finding)."""
    import subprocess, datetime, zoneinfo
    PT = zoneinfo.ZoneInfo("America/Los_Angeles")
    lp = os.path.join("development", "METHYLPHYS_DEVELOPMENT_LOG.md")
    out, t = [], None
    try: B = subprocess.run(["git", "blame", "--line-porcelain", lp], cwd=ROOT, capture_output=True, text=True, timeout=300).stdout.split("\n")
    except Exception: B = []
    for l in B:
        if l.startswith("author-time "): t = int(l.split()[1])
        elif l.startswith("\t### "):
            day = datetime.datetime.fromtimestamp(t, PT).date().isoformat() if t else datetime.datetime.now(PT).date().isoformat()
            m = re.match(r"\t### (\d{4}-\d{2}-\d{2}) . (.+)$", l)
            if m and "Day summary" not in m.group(2): out.append((day, m.group(1), m.group(2).strip()))
    return out

def today_pt():
    import datetime, zoneinfo
    return datetime.datetime.now(zoneinfo.ZoneInfo("America/Los_Angeles")).date().isoformat()

def coverage(d):
    """Committed development-log headings for this day whose content words do not appear in the rendered day log.

    Mechanical, not clever: it reports what to look at, so a day log cannot silently omit a thread that was committed that day.
    """
    import re
    lp = os.path.join(ROOT, "development", "METHYLPHYS_DEVELOPMENT_LOG.md")
    if not os.path.isfile(lp): return []
    heads = sorted({h for day, _, h in pacific_heads() if day == d["date"]})
    # author 2026-10-18 ("dont broadcast the temp test anywhere, it was exploratory and has no bearing on our instruments"): threads of the
    # manifest rows in the day log's off_page_rows are kept off the public day log; they stay in the development log, manifest and record
    off = set(d.get("off_page_rows", [])); heads = [h for h in heads if not any(o in h for o in off)]
    blob = set(re.findall(r"[a-z0-9-]+", render(d).lower()))
    out = []
    for h in heads:
        w = {x for x in re.findall(r"[a-z0-9-]+", h.lower()) if x not in STOP and len(x) > 3}
        ids = set(re.findall(r"\b(?:[A-Z]{2,}(?:-[A-Z0-9]+)*-\d{2,3}|[LB]\d{1,2})\b", h))
        txt = render(d)
        # covered only if its record id is named, or at least half of its content words appear (tightened 2026-10-14: one shared word is not coverage)
        if w and not (any(i in txt for i in ids) or len(w & blob) >= 0.5 * len(w)): out.append(h)
    return out

def build():
    P, days = [], []
    for p in sorted(glob.glob(os.path.join(SRC, "*.json"))):
        d = json.load(open(p, encoding="utf-8")); P += one(d, p); days.append(d)
    idx = ["# Day logs — shift turnover", "",
           "_One per day, generated from `CANON/daylogs/` by `CANON/daylog.py`. Each is what a researcher or a donor would need to "
           "follow that day: what ran, what passed, what failed, what we learned, the thinking that produced it, and what changed in "
           "the plan. Newest first._", "", "| date | the day |", "|---|---|"]
    for d in sorted(days, key=lambda x: x["date"], reverse=True):
        idx.append(f"| [{d['date']}]({d['date']}.md) | {d['title']} |")
    return days, P, "\n".join(idx) + "\n"

if __name__ == "__main__":
    days, P, idx = build()
    if "--coverage" in sys.argv:
        for d in days:
            m = coverage(d)
            print(f"{d['date']}: {len(m)} committed log heading(s) with no overlap in the day log")
            for x in m: print("   -", x[:90])
        sys.exit(0)
    files = {os.path.join(OUT, d["date"] + ".md"): render(d) for d in days}
    files[os.path.join(OUT, "README.md")] = idx
    P += page_lists_every_day(days)
    # Enforced, not reported (author 2026-10-14: "Are we confirming the code is demanding perfection with this?"): once a Pacific day is
    # over, its day log must exist, must not be in progress, and must cover every development-log thread committed that day.
    have = {d["date"]: d for d in days}; tp = today_pt()
    for day in sorted({x[0] for x in pacific_heads() if "2026-10-14" <= x[0] < tp}):
        d = have.get(day)
        if not d: P.append(f"[daylog] {day}: the day is over and has no day log"); continue
        if re.search(r"(?i)in progress", (d.get("title", "") + " " + str(d.get("open_at_turnover", "")) + " " + d.get("set_out", ""))):
            P.append(f"[daylog] {day}: the day is over and its log still says in progress")
        for h in coverage(d): P.append(f"[daylog] {day}: committed thread missing from the day log: {h[:80]}")
        try: _cs = json.load(open(os.path.join(ROOT, "CANON", "compute_snapshot.json"))).get("as_of", "")
        except Exception: _cs = ""
        if _cs < day: P.append(f"[daylog] {day}: the campaign counts (CANON/compute_snapshot.json, as of {_cs}) predate this closed day: run python3 CANON/compute_snapshot.py")
        c = d.get("compute")   # author 2026-10-19: the day's computing and cost, demanded with the day log; the page reads it
        if not c: P.append(f"[daylog] {day}: the day is over and has no computing-and-cost block: run python3 CANON/day_compute.py")
        elif not c.get("final") and c.get("read", "") < (__import__("datetime").date.fromisoformat(tp) - __import__("datetime").timedelta(days=1)).isoformat():
            P.append(f"[daylog] {day}: its computing-and-cost block was read {c.get('read')} and is not final: run python3 CANON/day_compute.py")
    if "--check" in sys.argv:
        for f, t in files.items():
            cur = open(f, encoding="utf-8").read() if os.path.isfile(f) else ""
            if cur.strip() != t.strip(): P.append(f"[daylog] {os.path.basename(f)} differs from its source: run python3 CANON/daylog.py")
        print("daylog: " + ("ok (" + str(len(days)) + " day(s))" if not P else "REFUSED:\n  " + "\n  ".join(P))); sys.exit(1 if P else 0)
    os.makedirs(OUT, exist_ok=True)
    for f, t in files.items(): open(f, "w", encoding="utf-8").write(t)
    print(f"daylog: wrote {len(files)} file(s)" + ("" if not P else " WITH PROBLEMS:\n  " + "\n  ".join(P)))
