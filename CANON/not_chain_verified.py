#!/usr/bin/env python3
"""Not-chain-verified register (author 2026-10-15): every doors record whose synthetic test does not import the chain is listed here as
history, NOT CHAIN-VERIFIED, until it is rerun through the chain (CANON/chain_gate.py, rule 23b, applies to every test from 2026-10-15).
Generated; checkpoint.sh runs it. Writes Biological_Physics/MethylPhys/NOT_CHAIN_VERIFIED.md."""
import re, os, glob, json, sys
def section():
    D = "Biological_Physics/MethylPhys/doors/"; CI = re.compile(r"(?m)^\s*(from|import)\s+(conductor_v3|stage_\w+|dev_stages|cmb_tools|sky_statistics)\b")
    M = json.load(open("CANON/manifest.json"))["rows"]; R = {}
    for r in M:
        if r.get("record"): R.setdefault(r["record"], []).append(r["id"])
    IAMA_GATE = {"DEV_SECONDLAB_01", "DEV_BACKBONE_01"}
    rows = []
    for f in sorted(glob.glob(D + "*.md")):
        t = open(f, encoding="utf-8", errors="replace").read(); n = os.path.basename(f)[:-3]
        for l in t.split("\n"):
            if not l.startswith("**Synthetic test:**"): continue
            for x in re.findall(r"[A-Za-z0-9_/.-]+\.(?:py|sh)", l):
                p = D + "data/" + x
                if os.path.isfile(p) and not CI.search(open(p, encoding="utf-8", errors="replace").read()):
                    rows.append((n, x, "declares NO CHAIN" if "# NO CHAIN" in open(p, encoding="utf-8", errors="replace").read() else "no chain import", ", ".join(R.get(f, [])[:6])))
    L = ["# Not chain-verified (generated by CANON/not_chain_verified.py; do not edit by hand)", "",
         "Author's rule, 2026-10-15: side scripts are for exploration; every logged test runs through the chain. These records predate that rule:",
         "their synthetic tests ran on their own code. They stay as history and are marked NOT CHAIN-VERIFIED until rerun through the chain. Every",
         "test from 2026-10-15 on is held to the rule by the push gate (CANON/chain_gate.py, rule 23b).", "",
         "**Also not chain-verified: the self-reference line itself** (development/loose_share_2026-10-15/, own-read counts of Loyfer's 153 samples).",
         "It is rebuilt through chain Stage Q2 before any IAM-A test uses it (OTH-057).", "",
         f"**{len(rows)} synthetic tests.** Rerun first: the ones IAM-A's commissioning depends on, marked *IAM-A gate*.", "",
         "| record | synthetic script | why | manifest rows |", "|---|---|---|---|"]
    for n, x, w, m in sorted(rows, key=lambda r: (r[0] not in IAMA_GATE, r[0])):
        L.append(f"| {n}{' *IAM-A gate*' if n in IAMA_GATE else ''} | `{x}` | {w} | {m} |")
    return L, rows
if __name__ == "__main__":
    sys.path.insert(0, "CANON"); import pointer
    L, rows = section()
    pointer.write(".", "Biological_Physics/MethylPhys/NOT_CHAIN_VERIFIED.md", "Biological_Physics/MethylPhys/REPLICATE.md", "The list of older tests not yet run through the chain")
    print("not_chain_verified:", len(rows), "(section of REPLICATE.md)")
