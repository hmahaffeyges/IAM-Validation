#!/usr/bin/env python3
"""CANON/physics_root_tex.py - writes docs/book/part6/p6_19a_physics_root.tex from CANON/physics_root.md, the one source of why the chain
works (IAM's physics), which the instrument catalogue, the Operator Guide and the Chain Decoder also open with. Never edit the .tex by hand.
Usage: python3 CANON/physics_root_tex.py [--check]"""
import os, re, sys
import sys as _cs; _cs.path.insert(0, os.path.dirname(os.path.abspath(__file__))); from canon_fill import fill as _canon_fill   # 2026-11-06: physics values only from the canon
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "CANON", "physics_root.md"); OUT = os.path.join(ROOT, "docs", "book", "part6", "p6_19a_physics_root.tex")

def inline(s):
    s = s.replace("%", "\\%").replace("&", "\\&").replace("_B T", "@KBT@")
    s = re.sub(r"\*\*(.+?)\*\*", r"\\textbf{\1}", s)
    s = re.sub(r'"([^"]+)"', r"``\1''", s)
    return s.replace("@KBT@", "$\\,k_BT$").replace("k$\\,k_BT$", "$k_BT$")

def tex():
    lines = _canon_fill(open(SRC, encoding="utf-8").read()).strip().split("\n"); out = ["% Generated by CANON/physics_root_tex.py from CANON/physics_root.md; do not edit."]
    blocks, cur = [], []
    for l in lines:
        if l.startswith("# "): out.append("\\section{" + inline(l[2:]) + "}\\label{sec:physics_root}"); continue
        if not l.strip(): blocks.append(cur); cur = []; continue
        cur.append(l)
    blocks.append(cur)
    for b in [x for x in blocks if x]:
        items, kind = [], None
        for l in b:
            m = re.match(r"^(\d+)\. (.*)", l); n = re.match(r"^- (.*)", l)
            if m: items.append(m.group(2)); kind = "enumerate"
            elif n: items.append(n.group(1)); kind = "itemize"
            elif items: items[-1] += " " + l.strip()
            else: items.append(l.strip()); kind = kind or "par"
        if kind == "par": out.append(inline(" ".join(items)) + "\n")
        else:
            lead = [] if re.match(r"^(\d+\. |- )", b[0]) else [inline(items.pop(0))]
            out += lead + [f"\\begin{{{kind}}}"] + ["\\item " + inline(i) for i in items] + [f"\\end{{{kind}}}", ""]
    return "\n".join(out).rstrip() + "\n"

if __name__ == "__main__":
    t = tex()
    if "--check" in sys.argv:
        cur = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if cur != t: print(f"physics_root_tex: {os.path.relpath(OUT, ROOT)} differs from {os.path.relpath(SRC, ROOT)}; run without --check"); sys.exit(1)
        print("physics_root_tex: ok"); sys.exit(0)
    open(OUT, "w", encoding="utf-8").write(t); print(f"physics_root_tex: wrote {os.path.relpath(OUT, ROOT)}")
