#!/usr/bin/env python3
"""CANON/atlas_story.json -> the IAM-Atlas v2.1 story in the repository README and the book (author, 2026-10-16: one commentary feeds the repo,
the webpage and the book). The page builder reads the JSON directly.
Writes: Biological_Physics/MethylPhys/atlas/v2.1/README.md (between STORY markers, top of file) and docs/book/part6/p6_14b_atlas_v21.tex.
--check: refuse an unknown status, a tool without its cosmology, cell and use lines, or a README/book section that differs from what this writes."""
import json, os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
J = json.load(open(os.path.join(ROOT, "CANON", "atlas_story.json"), encoding="utf-8"))
RD = os.path.join(ROOT, "Biological_Physics/MethylPhys/atlas/v2.1/README.md"); TX = os.path.join(ROOT, "docs/book/part6/p6_14b_atlas_v21.tex")
LABEL = {"now": "in IAM-Atlas v2.1", "gift": "complementary additions, ready or in progress", "after": "on the horizon"}
P = [f"tool {t.get('name')}: status {t.get('status')!r}" for t in J["tools"] if t.get("status") not in LABEL]
P += [f"tool {t.get('name')}: missing {k}" for t in J["tools"] for k in ("sky", "cell", "them", "record") if not t.get(k)]
B, E_ = "<!-- STORY:BEGIN (generated by CANON/atlas_story.py from CANON/atlas_story.json; do not edit by hand) -->", "<!-- STORY:END -->"
def md():
    L = [B, f"## {J['title']}", ""] + [p + "\n" for p in J["opening"]] + [J["not_this"], ""]
    for st in ("now", "gift", "after"):
        T = [t for t in J["tools"] if t["status"] == st]
        L += [f"### The tools, {LABEL[st]}", "", "| tool | in cosmology | in IAM-Atlas v2.1 | IAM-Atlas's unique capability |", "|---|---|---|---|"]
        L += [f"| **{t['name']}** | {mdx(t['sky'])} | {mdx(t['cell'])} | {mdx(t['them'])} |" for t in T] + [""]
    L += ruler_md()
    L += [f"**What is commissioned.** {mdx(J['commissioned'])}", ""] + ([f"**The IAM Sequencing Atlas (in development).** {mdx(J['sequencing_atlas'])}", ""] if J.get("sequencing_atlas") else []) + [f"*{J['closing']}*", E_]
    return "\n".join(L)
def ruler_md(h="###"):
    """2026-11-07 (author): what makes the atlases a ruler for healthy, and who their donors were; one text for README, book, Q&A and site."""
    R = J.get("ruler")
    if not R: return []
    L = [f"{h} {R['question']}", "", R["answer"], ""] + [f"- **{x['name']}.** {x['text']}" for x in R["points"]] + ["", R["other_atlases"], "", R["not_the_reason"], "",
         R["donors_intro"], ""] + [f"- **{d['atlas']}:** {d['what']}" for d in R["donors"]] + ["", R["donors_meaning"], ""]
    return L
def ruler_tex():
    R = J.get("ruler")
    if not R: return []
    L = ["\\subsection*{" + tx(R["question"]) + "}", tx(R["answer"]), "", "\\begin{description}"] + ["\\item[" + tx(x["name"]) + ".] " + tx(x["text"]) for x in R["points"]]
    L += ["\\end{description}", "", tx(R["other_atlases"]), "", tx(R["not_the_reason"]), "", tx(R["donors_intro"]), "", "\\begin{description}"]
    L += ["\\item[" + tx(d["atlas"]) + ".] " + tx(d["what"]) for d in R["donors"]] + ["\\end{description}", "", tx(R["donors_meaning"]), ""]
    return L
QA = os.path.join(ROOT, "Biological_Physics/MethylPhys/QUESTIONS_AND_ANSWERS.md"); QB, QE = "<!-- RULER (generated by CANON/atlas_story.py from CANON/atlas_story.json; do not edit) -->", "<!-- /RULER -->"
def qa_new():
    s = open(QA, encoding="utf-8").read(); R = J.get("ruler")
    body = "\n".join([QB, f"**{R['question']}**", ""] + ruler_md("####")[2:] + [QE])
    if QB in s: return s[:s.index(QB)] + body + s[s.index(QE) + len(QE):]
    k = "## Samples, baselines and cell mix\n"; assert k in s
    return s.replace(k, k + "\n" + body + "\n", 1)
def mdx(t): return re.sub(r"@@ref:[a-z:]+@@", "its own chapter of the book", t)
def tx(t):
    t = t.replace("\\", "\\textbackslash{}")
    for a, b in (("&", "\\&"), ("%", "\\%"), ("$", "\\$"), ("#", "\\#"), ("_", "\\_"), ("{", "\\{"), ("}", "\\}")): t = t.replace(a, b)
    t = t.replace("\\textbackslash\\{\\}", "\\textbackslash{}")
    t = re.sub(r"(\d) (?=\\%)", r"\1~", t)
    return re.sub(r"@@ref:([a-z:]+)@@", r"Chapter~\\ref{\1}", t)   # 2026-11-05: a chapter reference survives the escaping (it printed raw code)
def tex():
    L = ["% Generated by CANON/atlas_story.py from CANON/atlas_story.json; do not edit by hand.",
         "\\section{" + tx(J["title"]) + "}\\label{sec:atlas:v21story}", ""] + [tx(p) + "\n" for p in J["opening"]] + [tx(J["not_this"]), ""]
    for st in ("now", "gift", "after"):
        L += ["\\subsection*{The tools, " + LABEL[st] + "}", "\\begin{description}"]
        for t in [t for t in J["tools"] if t["status"] == st]:
            L += ["\\item[" + tx(t["name"]) + ".] \\emph{In cosmology:} " + tx(t["sky"]) + " \\emph{In the atlas:} " + tx(t["cell"]) + " \\emph{IAM-Atlas's unique capability:} " + tx(t["them"])]
        L += ["\\end{description}", ""]
    L += ruler_tex()
    L += ["\\paragraph{What is commissioned.} " + tx(J["commissioned"]), ""] + (["\\paragraph{The IAM Sequencing Atlas (in development).} " + tx(J["sequencing_atlas"]), ""] if J.get("sequencing_atlas") else []) + ["\\emph{" + tx(J["closing"]) + "}", ""]
    return "\n".join(L)
def readme_new():
    s = open(RD, encoding="utf-8").read()
    if B in s: s = s[:s.index(B)] + md() + s[s.index(E_) + len(E_):]
    else: s = md() + "\n\n" + s
    return s
if "--check" in sys.argv:
    if open(RD, encoding="utf-8").read() != readme_new(): P.append("atlas/v2.1/README.md story differs (run python3 CANON/atlas_story.py)")
    if not os.path.exists(TX) or open(TX, encoding="utf-8").read() != tex(): P.append("p6_14b_atlas_v21.tex differs (run python3 CANON/atlas_story.py)")
    if J.get("ruler") and open(QA, encoding="utf-8").read() != qa_new(): P.append("QUESTIONS_AND_ANSWERS.md ruler entry differs (run python3 CANON/atlas_story.py)")
    print("atlas_story: " + ("ok" if not P else "REFUSED\n  " + "\n  ".join(P))); sys.exit(1 if P else 0)
if P: print("atlas_story: REFUSED\n  " + "\n  ".join(P)); sys.exit(1)
_new = readme_new()   # read before opening for write (opening truncates the file)
_qa = qa_new() if J.get("ruler") else None
open(RD, "w", encoding="utf-8").write(_new); open(TX, "w", encoding="utf-8").write(tex()); (open(QA, "w", encoding="utf-8").write(_qa) if _qa else None); print("atlas_story: written")
