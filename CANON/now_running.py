"""Now running board (author 2026-10-12: give followers a show; most are not scientists). Writes the block between NOW_RUNNING markers in
README.md and FOLLOW.md from CANON/now_running.json. --check (run by status_check) refuses: a block that differs from the file; a status outside
the allowed set; an update without a date or with a record that does not exist; a story whose newest update is more than 7 days old unless its
status is 'result'; hype words; the wrong voice (the notes are ours, written as "we"); FIELD_NOTES.md differing from the file; and (append-only, author 2026-10-12) any update published on
origin/main that is now edited or missing. The board shows the newest three updates per story; FIELD_NOTES.md keeps every update with its note.
Usage: python3 CANON/now_running.py [--check]"""
import subprocess
import os, re, sys, json, datetime
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
B, E = "<!-- NOW_RUNNING:BEGIN (generated by CANON/now_running.py from CANON/now_running.json; do not edit by hand) -->", "<!-- NOW_RUNNING:END -->"
STATUS = {"getting ready": "Getting ready", "running": "Running now", "on hold": "On hold", "result": "Result is in"}
# Voice (author 2026-10-12): the notes are ours, written as "we"; never "the author", never an assistant reporting, never first-person singular.
VOICE = re.compile(r"\b(the author|author's|assistant|Claude|Walther|I'll|I will|I'm|I've|I|me|my)\b")
HYPE = re.compile(r"\b(cure[sd]?|breakthrough|guarantee[sd]?|proves?|proven|miracle|revolutionary|game.?changer)\b", re.I)
def problems(J):
    P = []; today = datetime.date.today()
    for s in J["stories"]:
        if s["status"] not in STATUS: P.append(f"{s['id']}: status '{s['status']}'")
        for u in s["updates"]:
            if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", u.get("date", "")): P.append(f"{s['id']}: update without a date")
            if not os.path.exists(os.path.join(ROOT, u.get("record", ""))): P.append(f"{s['id']}: record not found: {u.get('record')}")
        last = max(datetime.date.fromisoformat(u["date"]) for u in s["updates"])
        if s["status"] != "result" and (today - last).days > 7: P.append(f"{s['id']}: newest update {last} is more than 7 days old")
        txt = " ".join([s["headline"], s["why"], s["hope"], s["risk"]] + [u["text"] + " " + u.get("note", "") for u in s["updates"]])
        if HYPE.search(txt): P.append(f"{s['id']}: hype word '{HYPE.search(txt).group(0)}'")
        if VOICE.search(txt): P.append(f"{s['id']}: voice '{VOICE.search(txt).group(0)}' (write as we, our notes)")
    return P
def block(J, rel):
    L = [B, "", "## Now running", "", "*Live experiments, in plain words. Each update links to its record. Results are posted here win or lose.*", ""]
    for s in J["stories"]:
        L += [f"### {s['headline']}", "", f"**{STATUS[s['status']]}.** {s['why']}", "", f"- **What we hope:** {s['hope']}", f"- **What could go wrong:** {s['risk']}", ""]
        U = sorted(enumerate(s["updates"]), key=lambda t: (t[1]["date"], t[0]), reverse=True)[:3]
        L += ["| date | update |", "|---|---|"] + [f"| {u['date']} | {u['text']} [record]({rel}{u['record']}) |" for _, u in U]
        L += ["", f"*The full story so far, every update in plain words: [field notes]({rel}FIELD_NOTES.md#{s['id'].replace('_', '-')}).*", ""]
    return "\n".join(L + [E])
def notes(J):
    L = ["# Field notes", "", "*Every update to every experiment on the Now running board, in plain words, oldest first. Notes are never edited or removed;",
         "a correction is a new note. Generated from CANON/now_running.json by CANON/now_running.py; do not edit by hand.*", ""]
    for s in J["stories"]:
        L += [f'<a id="{s["id"].replace("_", "-")}"></a>', f"## {s['headline']}", "", f"*{STATUS[s['status']]}.* {s['why']}", ""]
        for i, u in sorted(enumerate(s["updates"]), key=lambda t: (t[1]["date"], t[0])):
            L += [f"### {u['date']} · {u['text']}", ""] + ([u["note"], ""] if u.get("note") else []) + [f"Record: [{os.path.basename(u['record'])}]({u['record']})", ""]
    return "\n".join(L)
def published():
    r = subprocess.run(["git", "-C", ROOT, "show", "origin/main:CANON/now_running.json"], capture_output=True, text=True)
    return json.loads(r.stdout) if r.returncode == 0 else {"stories": []}
def appendonly(J):
    P = []; cur = {s["id"]: s["updates"] for s in J["stories"]}
    for s in published()["stories"]:
        now = cur.get(s["id"])
        if now is None: P.append(f"story {s['id']} was removed (append-only)"); continue
        for u in s["updates"]:
            if u not in now:
                old = [x for x in now if x["date"] == u["date"] and x["text"] == u["text"] and x["record"] == u["record"]]
                if old and "note" not in u: continue   # a note may be ADDED to an update that had none; nothing else may change
                P.append(f"{s['id']}: published update of {u['date']} was edited or removed (append-only; add a new update instead)")
    return P
def apply(path, J, write):
    t = open(path, encoding="utf-8").read(); b = block(J, "")
    if B in t: new = t[:t.index(B)] + b + t[t.index(E) + len(E):]
    else: return None
    if write and new != t: open(path, "w", encoding="utf-8").write(new)
    return new == t
if __name__ == "__main__":
    J = json.load(open(os.path.join(ROOT, "CANON", "now_running.json"), encoding="utf-8")); P = problems(J)
    files = [os.path.join(ROOT, f) for f in ("README.md", "FOLLOW.md")]
    FN = os.path.join(ROOT, "FIELD_NOTES.md")
    if "--check" in sys.argv:
        P += appendonly(J)
        if not os.path.exists(FN) or open(FN, encoding="utf-8").read() != notes(J): P.append("FIELD_NOTES.md differs from CANON/now_running.json (run python3 CANON/now_running.py)")
        for f in files:
            r = apply(f, J, False)
            if r is None: P.append(f"{os.path.basename(f)}: no NOW_RUNNING markers")
            elif not r: P.append(f"{os.path.basename(f)}: board differs from CANON/now_running.json (run python3 CANON/now_running.py)")
        print("now_running: " + ("ok" if not P else "REFUSED: " + "; ".join(P))); sys.exit(1 if P else 0)
    if P: raise SystemExit("now_running: " + "; ".join(P))
    P = appendonly(J)
    if P: raise SystemExit("now_running: " + "; ".join(P))
    for f in files: apply(f, J, True)
    open(FN, "w", encoding="utf-8").write(notes(J)); print("now_running: written (board and FIELD_NOTES.md)")
