"""The Master Testing Manifest: every test of the project, past, current and future, numbered, in one file (CANON/manifest.json),
written out as MANIFEST.md at the repository root. Never edited by hand: edit the json, run this script.

Rules, enforced by --check (run by status_check):
  1. every row has a unique, stable id SECTION-NNN; once an id exists it is never removed or renumbered (compared with the last commit);
  2. a test is never deleted: finishing it adds a dated entry to its "runs" (date, outcome success|fail|progressed|inconclusive|invalid);
  3. every "record" path exists in the repository;
  4. every lever in CANON/levers.json and every instrument in CANON/instruments.json has a manifest row;
  5. MASTER_INVENTORY.md and TODO.md... see the generated views: MANIFEST.md (full) and TODO.md (open rows only, by impact) are
     generated from the json and must match it.
Usage: python3 CANON/manifest.py [--check]
"""
import json, os, re, subprocess, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "CANON", "manifest.json"); OUT = os.path.join(ROOT, "MANIFEST.md"); TODO = os.path.join(ROOT, "TODO.md")
OUTCOMES = {"success", "fail", "progressed", "inconclusive", "invalid"}
STATUS = ["idea", "planned", "designed", "synthetic_done", "sealed", "run", "parked", "retired"]
CLOSED = {"run", "retired"}
def load(): return json.load(open(SRC, encoding="utf-8"))
def esc(x): return str(x or "").replace("|", "/").replace("\n", " ")
def link(p): return f"[{os.path.basename(p).replace('.md', '')}]({p})" if p else ""
def runs_txt(r):
    return "<br>".join(f"**{x['date']}** {x['outcome'].upper()}: {esc(x.get('note'))}" for x in r.get("runs", [])) or "not run"
def render(J):
    S = {s["code"]: s for s in J["sections"]}; R = J["rows"]
    L = ["# Master Testing Manifest", "", "_Generated by `CANON/manifest.py` from `CANON/manifest.json`; never edited by hand. Every test of the "
         "project, numbered. A test is never removed: when it runs, it gets a dated result. Ask for any test by its number._", "",
         f"**{len(R)} tests** · {sum(1 for r in R if r['runs'])} with at least one run · {sum(1 for r in R if r['status'] not in CLOSED)} open · "
         f"sections: " + ", ".join(f"[{c}](#{c.lower()})" for c in S), "",
         "Columns: **#** the test number · **Test** · **What it is for, and why it matters** · **Instrument / term** · **Data** (sources, and whether we "
         "have them) · **Status** · **Runs** (date, result) · **Next** · **Cost** (laptop, box, search) · **Impact** (5 = most) · **Record**.", ""]
    for c, s in S.items():
        rows = [r for r in R if r["id"].startswith(c + "-")]
        L += [f"## {c}", "", f"**{s['title']}.** {s['about']}", "",
              "| # | Test | What it is for, and why it matters | Instrument / term | Data | Status | Runs | Next | Cost | Impact | Record |",
              "|---|---|---|---|---|---|---|---|---|---|---|"]
        for r in rows:
            data = esc(", ".join(r.get("sources", [])) or "-") + f" · *{esc(r.get('data_status'))}*"
            L.append(f"| **{r['id']}** | {esc(r['title'])} | {esc(r['purpose'])} | {esc(r.get('instrument_or_term'))} | {data} | {esc(r['status'])} | "
                     f"{runs_txt(r)} | {esc(r.get('next_step'))} | {esc(r.get('cost'))} | {r.get('impact', '')} | {link(r.get('record'))} |")
        L.append("")
    return "\n".join(L) + "\n"
def render_todo(J):
    R = sorted([r for r in J["rows"] if r["status"] not in CLOSED], key=lambda r: (-int(r.get("impact") or 0), r["id"]))
    L = ["# To do: every open test, most impactful first", "", "_Generated by `CANON/manifest.py` from `CANON/manifest.json`; the full list, with "
         "every finished test and its result, is [MANIFEST.md](MANIFEST.md)._", ""]
    L += [f"- [ ] **{r['id']}** (impact {r.get('impact')}, {esc(r.get('cost'))}) {esc(r['title'])}: {esc(r.get('next_step'))}" for r in R]
    done = [r for r in J["rows"] if r["runs"]]
    L += ["", "## Run at least once", ""] + [f"- [x] **{r['id']}** {esc(r['title'])}: last run {r['runs'][-1]['date']}, {r['runs'][-1]['outcome']}" for r in done]
    return "\n".join(L) + "\n"
def problems(J):
    P = []; ids = [r["id"] for r in J["rows"]]; codes = {s["code"] for s in J["sections"]}
    for i in sorted({i for i in ids if ids.count(i) > 1}): P.append(f"duplicate id {i}")
    for r in J["rows"]:
        if not re.fullmatch(r"[A-Z]+(-[A-Z]+)?-\d{3}", r["id"]) or r["id"].rsplit("-", 1)[0] not in codes: P.append(f"{r['id']}: bad id or unknown section")
        if r["status"] not in STATUS: P.append(f"{r['id']}: status {r['status']!r}")
        for x in r.get("runs", []):
            if x.get("outcome") not in OUTCOMES or not re.fullmatch(r"\d{4}-\d{2}-\d{2}", x.get("date", "")): P.append(f"{r['id']}: run {x}")
        if r.get("record") and not os.path.exists(os.path.join(ROOT, r["record"])): P.append(f"{r['id']}: record {r['record']} does not exist")
        if not r.get("purpose"): P.append(f"{r['id']}: no purpose")
    try:
        old = json.loads(subprocess.run(["git", "show", "HEAD:CANON/manifest.json"], cwd=ROOT, capture_output=True, text=True, check=True).stdout)
        gone = sorted({r["id"] for r in old["rows"]} - set(ids)); P += [f"{i} was removed (a test is never removed; give it a run or status retired)" for i in gone]
        for r in old["rows"]:
            new = next((x for x in J["rows"] if x["id"] == r["id"]), None)
            if new and len(new.get("runs", [])) < len(r.get("runs", [])): P.append(f"{r['id']}: a dated run was removed")
    except Exception: pass
    lv = json.load(open(os.path.join(ROOT, "CANON", "levers.json"), encoding="utf-8"))["levers"]
    ins = json.load(open(os.path.join(ROOT, "CANON", "instruments.json"), encoding="utf-8"))["instruments"]
    reg = {x for r in J["rows"] for x in r.get("register_ids", [])}
    for x in lv:
        k = x.get("id") or x.get("name")
        if k not in reg: P.append(f"lever {k!r} has no manifest row (register_ids)")
    for x in ins:
        k = x.get("id") or x.get("name")
        if k not in reg: P.append(f"instrument {k!r} has no manifest row (register_ids)")
    return P
if __name__ == "__main__":
    J = load(); P = problems(J); md, td = render(J), render_todo(J)
    if "--check" in sys.argv:
        for f, t in ((OUT, md), (TODO, td)):
            if not os.path.exists(f) or open(f, encoding="utf-8").read() != t: P.append(f"{os.path.basename(f)} differs from CANON/manifest.json (run python3 CANON/manifest.py)")
    else:
        open(OUT, "w", encoding="utf-8").write(md); open(TODO, "w", encoding="utf-8").write(td)
    print("manifest: " + (f"ok ({len(J['rows'])} tests)" if not P else "REFUSED:\n  " + "\n  ".join(P[:40])))
    sys.exit(1 if P else 0)
