"""The lever register is the single source for the lever chapter and for DEV-LEVERS-01.

Checks, run by status_check:
 1. every lever has a falsifier - the reading that would break IAM there. A lever without one is a demonstration, not a test.
 2. every term a lever claims to move is an id in CANON/foundation.json, so the chapter cannot invoke physics the foundation
    does not carry.
 3. every record and synthetic-test file a lever names exists.
 4. the generated section in DEV_LEVERS_01.md matches the register (write it with --write).

Usage: python3 CANON/levers_check.py [--write]
"""
import json, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
L = json.load(open(os.path.join(ROOT, "CANON", "levers.json"), encoding="utf-8"))
F = json.load(open(os.path.join(ROOT, "CANON", "foundation.json"), encoding="utf-8"))
IDS = {e["id"] for e in F["entries"]}
NOTE = os.path.join(ROOT, "Biological_Physics/MethylPhys/doors/DEV_LEVERS_01.md")
B, E = "<!-- LEVERS:BEGIN (generated by CANON/levers_check.py --write from CANON/levers.json; do not edit by hand) -->", "<!-- LEVERS:END -->"
DATA = "Biological_Physics/MethylPhys/doors/data/"

def section():
    out = [B, "", "## The levers, one record each (generated from `CANON/levers.json`)", ""]
    for x in L["levers"]:
        out += [f"### {x['name']}", "",
                f"- **Term of the law it moves:** {', '.join(x['moves'])} (`CANON/foundation.json`)",
                f"- **Mechanism:** {x['mechanism']}",
                f"- **Derivation:** {x['derivation']}",
                f"- **Parameter-free prediction:** {x['parameter_free']}",
                f"- **Caveat:** {x['caveat']}",
                f"- **Synthetic test:** {', '.join(x['synthetic']) if x['synthetic'] else 'none yet'} - {x['synthetic_outcome']}",
                f"- **Data it needs:** {x['data']}",
                f"- **Status:** {x['status']}",
                f"- **FALSIFIER (written before any data is read):** {x['falsifier']}",
                f"- **Record:** [{os.path.basename(x['record'])}]({os.path.relpath(x['record'], 'Biological_Physics/MethylPhys/doors')})", ""]
    out += [E]
    return "\n".join(out)

def problems():
    P = []
    for x in L["levers"]:
        if not x.get("falsifier"): P.append(f"lever {x['id']}: no falsifier - a lever without one is a demonstration, not a test")
        for m in x.get("moves", []):
            if m not in IDS: P.append(f"lever {x['id']}: moves '{m}', which is not an entry in CANON/foundation.json")
        if not os.path.isfile(os.path.join(ROOT, x["record"])): P.append(f"lever {x['id']}: its record {x['record']} does not exist")
        for s in x.get("synthetic", []):
            if not os.path.isfile(os.path.join(ROOT, DATA + s)): P.append(f"lever {x['id']}: synthetic test {s} is not committed")
    t = open(NOTE, encoding="utf-8").read()
    if B not in t or E not in t: P.append("DEV_LEVERS_01.md has no generated lever section: run python3 CANON/levers_check.py --write")
    elif t[t.index(B):t.index(E) + len(E)].strip() != section().strip():
        P.append("DEV_LEVERS_01.md lever section differs from CANON/levers.json: run python3 CANON/levers_check.py --write")
    return P

if __name__ == "__main__":
    if "--write" in sys.argv:
        t = open(NOTE, encoding="utf-8").read()
        s = section()
        t = (t[:t.index(B)] + s + t[t.index(E) + len(E):]) if B in t and E in t else t.rstrip("\n") + "\n\n" + s + "\n"
        open(NOTE, "w", encoding="utf-8").write(t)
        print(f"levers_check: wrote the section for {len(L['levers'])} levers into DEV_LEVERS_01.md")
        sys.exit(0)
    P = problems()
    print("levers_check: " + (f"ok ({len(L['levers'])} levers, all with falsifiers)" if not P else "REFUSED:\n  " + "\n  ".join(P)))
    sys.exit(1 if P else 0)
