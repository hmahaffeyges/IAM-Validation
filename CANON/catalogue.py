"""The IAM instrument catalogue (author 2026-10-15). Writes Biological_Physics/MethylPhys/INSTRUMENTS.md and the README block between CATALOGUE markers from
CANON/catalogue.json; every status line is computed from the Master Testing Manifest rows each instrument names. The page builds its
catalogue section from the same functions. --check refuses: a block or file that differs from the source, a named row that does not exist,
a hype word or the wrong voice.
Usage: python3 CANON/catalogue.py [--check]"""
import sys as _s, os as _o; _s.path.insert(0, _o.path.join(_o.path.dirname(_o.path.abspath(__file__)), "CANON") if _o.path.basename(_o.path.dirname(_o.path.abspath(__file__))) != "CANON" else _o.path.dirname(_o.path.abspath(__file__))); import relink as _rl
import os, sys, json, re
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
B, E = "<!-- CATALOGUE:BEGIN (generated by CANON/catalogue.py from CANON/catalogue.json and CANON/manifest.json; do not edit by hand) -->", "<!-- CATALOGUE:END -->"
OUTCOME = {"success": "met", "fail": "not met", "progressed": "progressed", "inconclusive": "inconclusive", "invalid": "invalid"}
STATUS = {"idea": "idea", "planned": "planned", "designed": "designed", "synthetic_done": "synthetic done", "sealed": "sealed, waiting for data",
          "running": "running now", "run": "run", "retired": "retired", "parked": "parked"}
def load():
    C = json.load(open(os.path.join(ROOT, "CANON", "catalogue.json"), encoding="utf-8"))
    M = {r["id"]: r for r in json.load(open(os.path.join(ROOT, "CANON", "manifest.json"), encoding="utf-8"))["rows"]}
    return C, M
def row_line(r):
    s = STATUS.get(r["status"], r["status"]); runs = r.get("runs") or []
    if runs: s += f"; last run {runs[-1]['date']}: {OUTCOME.get(runs[-1]['outcome'], runs[-1]['outcome'])}"
    return f"{r['id']} {r['title'].split(' (')[0]}: {s}"
def stage(inst, M):
    rows = [M[i] for i in inst["rows"] if i in M]
    if any(r["status"] == "running" for r in rows): return "running now"
    if inst["id"] == "meta": return "commissioned (isolated neutrophils)"
    if inst.get("commissioned"): return f"commissioned ({inst['commissioned']})"
    if any((r.get("runs") or [{}])[-1].get("outcome") == "success" for r in rows): return "passing its tests"
    return "in development"
def markdown(C, M):
    L = ["# The IAM instrument catalogue", "", "*Generated from CANON/catalogue.json; every status line comes from the Master Testing Manifest.*", "",
         "## Why a self-reference matters", "", C["why_self_reference"], "", "## How they work together", "", C["together"], ""]
    if C.get("methods"):   # lab methods and what each instrument reads (author's downtime item 3, 2026-10-16)
        L += ["## Lab methods: what the chemistry and the machines give, and which instrument reads each", "", C["chemistry_intro"], "",
              "| Method | What it gives | Single molecules? | Who uses it | Which IAM instruments read it |", "|---|---|---|---|---|"]
        L += [f"| **{m['name']}** | {m['what']} | {m['molecules']} | {m['industry']} | {m['readers']} |" for m in C["methods"]] + ["", C.get("cohort_note", ""), ""]
    for i in C["instruments"]:
        L += [f"## {i['name']}", "", f"**The question:** {i['question']}", "", i["how"], "", f"**Reads:** {i['reads']}. **Where it stands:** {stage(i, M)}.", ""]
        L += [f"- {row_line(M[r])}" for r in i["rows"] if r in M] + ["", f"**Next:** {i['next']}", ""]
    import instruments_board as IB   # the candidates board, merged here 2026-10-16 (one catalogue)
    cb, _ = IB.build(base=ROOT); cb = cb.split("\n")
    L += ["## Candidate instruments", ""] + [("#" + x) if x.startswith("## ") else x for x in cb if not x.startswith("# ") and "do not edit by hand" not in x] + [""]
    return "\n".join(L)
def table(C, M):
    L = [B, "", "| Instrument | The question it answers | Where it stands |", "|---|---|---|"]
    L += [f"| **{i['name']}** | {i['question']} | {stage(i, M)} |" for i in C["instruments"]]
    L += ["", "How each one works, why it matters, and every test behind it: [Biological_Physics/MethylPhys/INSTRUMENTS.md](Biological_Physics/MethylPhys/INSTRUMENTS.md).", "", E]
    return "\n".join(L)
def problems(C, M):
    sys.path.insert(0, os.path.join(ROOT, "CANON")); import now_running as NR
    P = [f"{i['id']}: manifest row {r} does not exist" for i in C["instruments"] for r in i["rows"] if r not in M]
    txt = " ".join([C["why_self_reference"], C["together"]] + [i[k] for i in C["instruments"] for k in ("question", "how", "next")])
    if NR.HYPE.search(txt): P.append(f"hype word '{NR.HYPE.search(txt).group(0)}'")
    if NR.VOICE.search(txt): P.append(f"voice '{NR.VOICE.search(txt).group(0)}' (write as we)")
    return P
if __name__ == "__main__":
    C, M = load(); P = problems(C, M); md = markdown(C, M) + "\n"; tb = table(C, M)
    rp = os.path.join(ROOT, "README.md"); r = open(rp, encoding="utf-8").read()
    if "--check" in sys.argv:
        if open(os.path.join(ROOT, "Biological_Physics/MethylPhys/INSTRUMENTS.md"), encoding="utf-8").read() != _rl.fix(md, os.path.join(ROOT, "Biological_Physics/MethylPhys/INSTRUMENTS.md")): P.append("Biological_Physics/MethylPhys/INSTRUMENTS.md differs: run python3 CANON/catalogue.py")
        if B not in r or r[r.index(B):r.index(E) + len(E)] != tb: P.append("README.md catalogue block differs: run python3 CANON/catalogue.py")
        print("catalogue: " + ("ok" if not P else "REFUSED")); [print("  " + p) for p in P]; sys.exit(1 if P else 0)
    if P: print("catalogue: REFUSED"); [print("  " + p) for p in P]; sys.exit(1)
    open(os.path.join(ROOT, "Biological_Physics/MethylPhys/INSTRUMENTS.md"), "w", encoding="utf-8").write(_rl.fix(md, os.path.join(ROOT, "Biological_Physics/MethylPhys/INSTRUMENTS.md")))
    if B in r: r = r[:r.index(B)] + tb + r[r.index(E) + len(E):]; open(rp, "w", encoding="utf-8").write(r)
    print("catalogue: wrote Biological_Physics/MethylPhys/INSTRUMENTS.md" + (" and the README block" if B in r else " (README has no CATALOGUE markers yet)"))
