#!/usr/bin/env python3
"""IAM in bits (author 2026-10-15): "translate our applications and make the connections all of it using computer language." Generates
development/bit_paper/BIT_TABLES.md from CANON/four_domains.json (every value already sourced to the book there); nothing is typed here
except the computer-language name of each row. Table 1: the connections, one row per computer term, each domain's own word.
Tables 2-5: one per application, the value, its status and its source. Usage: python3 CANON/bit_tables.py [--check]"""
import json, os, sys
R = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); J = json.load(open(os.path.join(R, "CANON/four_domains.json"), encoding="utf-8"))
S = {s["id"]: s for s in J["slots"]}; DOM = J["domains"]; NAME = {"cosmos": "Cosmos", "qubits": "Qubits", "chips": "Chips", "cells": "Cells"}
ROWS = [("Price per bit", "bit_price", "the least energy to write one bit at this surface (Landauer, at the surface's temperature)"),
        ("Capacity (bits stored)", "bits", "data at rest: what the surface holds"),
        ("Bits per operation", "bits_per_op", "a snapshot or a limit: the writing in one operation"),
        ("Bit rate", "bit_rate", "data in motion: bits per operation x operations per second"),
        ("Throughput", "throughput", "the most bits per second the system can process: power for writing / price per write"),
        ("Power budget per operation", "mahaffey", "the drive each operation can spend, in units of k_B T (divide by ln 2 for bits' worth)"),
        ("Operating point", "reference", "the system as built or healthy: where it is designed to run"),
        ("Gate error", "gate_error", "error of the writing step itself, the firm end"),
        ("Leakage", "leakage", "loss outside the held states, the loose end"),
        ("Floor", "floor", "the least writing the system can run on"),
        ("Saturation (capacity reached)", "ceiling", "the surface full: no more room to write"),
        ("Crash (overload)", "wall", "the load (bits per second demanded) exceeds throughput: the writing outruns what the surface can record"),
        ("Point of no return", "no_return", "past it the record cannot be undone")]
E = lambda t: str(t or "").replace("|", "/").replace("\n", " ")
def short(t, n=140):
    t = E(t)
    return t if len(t) <= n else t[:n].rsplit(" ", 1)[0].rstrip(",;:(") + " ..."
L = ["# IAM in bits: the applications in computer language", "",
     "**IAM is a model of how reality begins with a bit and the cost that comes with it.**", "",
     "Generated by `CANON/bit_tables.py` from `CANON/four_domains.json`; every value carries the book section it comes from and the book's own",
     "status. Do not edit by hand. Open means the book has no value yet.", "",
     "## Table 1. The connections: one computer term, four applications", "",
     "| Computer term | Meaning | " + " | ".join(NAME[d] for d in DOM) + " |", "|---|---|" + "---|" * len(DOM)]
for term, k, mean in ROWS:
    L.append(f"| **{term}** | {mean} | " + " | ".join(f"{short(S[k][d].get('native') or S[k][d].get('formula'))} *({S[k][d].get('status')})*" for d in DOM) + " |")
for i, d in enumerate(DOM, 2):
    L += ["", f"## Table {i}. {NAME[d]} in bits", "", "| Computer term | Value | Status | Source |", "|---|---|---|---|"]
    for term, k, _ in ROWS:
        e = S[k][d]; L.append(f"| **{term}** | {E(e.get('formula'))} | {e.get('status')} | {E(e.get('source'))} |")
OUT = "\n".join(L) + "\n"; P = os.path.join(R, "development/bit_paper/BIT_TABLES.md")
if sys.argv[1:] == ["--check"]:
    ok = os.path.exists(P) and open(P, encoding="utf-8").read() == OUT
    print("bit_tables: " + ("ok" if ok else "REFUSED: BIT_TABLES.md differs from CANON/four_domains.json (run python3 CANON/bit_tables.py)")); sys.exit(0 if ok else 1)
open(P, "w", encoding="utf-8").write(OUT); print("bit_tables: written", len(ROWS), "rows x", len(DOM), "applications")
