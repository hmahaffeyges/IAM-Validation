"""One funding statement, written to every place it appears (author request 2026-10-12). Source: CANON/funding.json (link and wording).
Places, each between markers: README.md and FOLLOW.md (<!-- FUNDING:BEGIN ... --> / <!-- FUNDING:END -->) and the book preface
docs/book/front/p0_preface.tex (% FUNDING:BEGIN / % FUNDING:END). write: rewrites every block from the source. check: exit 1 if any place is
missing its block or differs from the source (push-gate rule 18). Usage: python3 CANON/funding_sync.py write | check"""
import os, sys, json
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); os.chdir(ROOT)
F = json.load(open("CANON/funding.json", encoding="utf-8"))
MD = F["md"].replace("{url}", F["url"]); TEX = F["tex"].replace("{url}", F["url"])
PLACES = [("README.md", "<!-- FUNDING:BEGIN (generated by CANON/funding_sync.py from CANON/funding.json; do not edit by hand) -->", "<!-- FUNDING:END -->", MD),
          ("FOLLOW.md", "<!-- FUNDING:BEGIN (generated by CANON/funding_sync.py from CANON/funding.json; do not edit by hand) -->", "<!-- FUNDING:END -->", MD),
          ("docs/book/front/p0_preface.tex", "% FUNDING:BEGIN (generated by CANON/funding_sync.py from CANON/funding.json; do not edit by hand)", "% FUNDING:END", TEX)]
mode = sys.argv[1] if len(sys.argv) > 1 else "check"; bad = []
for f, b, e, body in PLACES:
    t = open(f, encoding="utf-8").read()
    if b not in t or e not in t: bad.append(f"{f}: no funding block"); continue
    i, j = t.index(b) + len(b), t.index(e)
    if mode == "write": open(f, "w", encoding="utf-8").write(t[:i] + "\n" + body + "\n" + t[j:])
    elif t[i:j].strip() != body.strip(): bad.append(f"{f}: funding block differs from CANON/funding.json")
if mode == "check":
    print("\n".join(bad) if bad else "funding_sync: ok"); sys.exit(1 if bad else 0)
