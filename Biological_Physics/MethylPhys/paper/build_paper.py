"""build_paper.py - the paper's numbers, filled from the canon and committed outputs (plan 50; written 2026-10-24).
Reads paper/values.json; for each draft (OUTLINE.md, METHODS_DRAFT.md and any *_DRAFT.md) writes paper/build/<name> with every {{name}}
replaced by its value, and paper/build/VALUES.md: each value, where it was read from, or 'pending' when its source does not exist yet.
Nothing is typed by hand; a value changes only when its source does.  Usage: python3 build_paper.py"""
import os, re, json, glob
H = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.abspath(os.path.join(H, "..", "..", ".."))
V = json.load(open(os.path.join(H, "values.json"), encoding="utf-8")); C = json.load(open(os.path.join(ROOT, "CANON", "iam_canon.json"), encoding="utf-8"))["constants"]
got, rows = {}, ["| value | reads | source |", "|---|---|---|"]
for k, v in V.items():
    if k.startswith("_"): continue
    if "canon" in v:
        x = C[v["canon"]]; got[k] = str(x["value"]); rows.append(f"| {k} | {got[k]} | CANON/iam_canon.json: {v['canon']} |"); continue
    p = os.path.join(ROOT, v["file"])
    if not os.path.exists(p): rows.append(f"| {k} | pending | {v['file']} (not yet written) |"); continue
    m = re.search(v["re"], open(p, encoding="utf-8").read(), re.M)
    got[k] = m.group(1).strip() if m else None; rows.append(f"| {k} | {got[k] if m else 'NOT FOUND'} | {v['file']} |")
# 2026-11-04 (author: the data we need goes in the paper, kept current): the outline's closing section names the fingerprint of the list it was
# written from; the build refuses while DATA_WE_NEED.md has changed since, so the paper cannot go out with an old list
import hashlib, sys
_dn = hashlib.sha256(open(os.path.join(H, "..", "DATA_WE_NEED.md"), "rb").read()).hexdigest()[:12]
_fp = re.search(r"data-list ([0-9a-f]{12})", open(os.path.join(H, "OUTLINE.md"), encoding="utf-8").read())
if not _fp or _fp.group(1) != _dn: sys.exit(f"build_paper: REFUSED: DATA_WE_NEED.md has changed (now {_dn}); rewrite the outline's closing section from it and set its fingerprint")
os.makedirs(os.path.join(H, "build"), exist_ok=True); miss = set()
for f in [os.path.join(H, "OUTLINE.md")] + sorted(glob.glob(os.path.join(H, "*_DRAFT.md"))):
    s = open(f, encoding="utf-8").read()
    def fill(m):
        n = m.group(1)
        if got.get(n) is None: miss.add(n); return f"[pending: {n}]"
        return got[n]
    open(os.path.join(H, "build", os.path.basename(f)), "w", encoding="utf-8").write(re.sub(r"\{\{(\w+)\}\}", fill, s))
open(os.path.join(H, "build", "VALUES.md"), "w", encoding="utf-8").write("# The paper's values, as read at build time\n\nGenerated by `build_paper.py` from `values.json`; do not edit.\n\n" + "\n".join(rows) + "\n")
print(f"build_paper: {len(got)} values read, {sum(1 for r in rows if '| pending |' in r)} pending, {len(miss)} placeholders unfilled {sorted(miss)}")
