"""The documents audit, step 1 (2026-11-10; author: search everything hand written over the past month, confirm it is accurate, and weigh
whether it can be generated from the canon; then consolidate). Reads only; changes nothing it keeps. On a full checkout:
  1. which files the canon's generators write: a marker file, then CANON/build_all.py, then every file newer than the marker (generated);
  2. every text document in the repository with its kind (generated, or hand-written), size and lines;
  3. the canon's own cross-document checks on the whole tree: number_trace, doc_audit, status_check, canon_check, each one's findings kept whole.
Writes xout/docs_generated.txt, xout/docs_all.csv, xout/check_<name>.txt and xout/docs_inventory_summary.txt."""
import os, sys, subprocess, time, csv
OUT = sys.argv[1] if len(sys.argv) > 1 else "xout"; os.makedirs(OUT, exist_ok=True)
SKIP = (".git/", "node_modules/", "archive/", "__pycache__")
EXT = (".md", ".tex", ".html", ".txt", ".json", ".csv", ".yml", ".py")
mark = os.path.join(OUT, ".marker"); open(mark, "w").write("x"); time.sleep(2); t0 = os.path.getmtime(mark)
r = subprocess.run([sys.executable, "CANON/build_all.py"], capture_output=True, text=True)
open(os.path.join(OUT, "check_build_all.txt"), "w").write(r.stdout + r.stderr)
gen, rows = set(), []
for d, ds, fs in os.walk("."):
    if any(s in d + "/" for s in SKIP) or d.startswith("./" + OUT): continue
    for f in fs:
        p = os.path.relpath(os.path.join(d, f))
        if not p.endswith(EXT): continue
        new = os.path.getmtime(p) > t0
        if new: gen.add(p)
        try: n = sum(1 for _ in open(p, encoding="utf-8", errors="ignore"))
        except Exception: n = -1
        rows.append(dict(path=p, kind="generated" if new else "hand-written or data", bytes=os.path.getsize(p), lines=n))
open(os.path.join(OUT, "docs_generated.txt"), "w").write("\n".join(sorted(gen)) + "\n")
with open(os.path.join(OUT, "docs_all.csv"), "w", newline="") as fh:
    w = csv.DictWriter(fh, fieldnames=["path", "kind", "bytes", "lines"]); w.writeheader(); w.writerows(sorted(rows, key=lambda x: x["path"]))
S = [f"generated by build_all: {len(gen)} files; text files in all: {len(rows)}"]
for name, cmd in (("number_trace", ["CANON/number_trace.py", "--check"]), ("doc_audit", ["CANON/doc_audit.py", "--check"]),
                  ("status_check", ["CANON/status_check.py"]), ("canon_check", ["CANON/canon_check.py"])):
    if not os.path.exists(cmd[0]): S.append(f"{name}: not present"); continue
    r = subprocess.run([sys.executable] + cmd, capture_output=True, text=True); t = r.stdout + r.stderr
    open(os.path.join(OUT, f"check_{name}.txt"), "w").write(t)
    S.append(f"{name}: exit {r.returncode}; {len(t.splitlines())} lines; last: {(t.strip().splitlines() or [''])[-1][:300]}")
open(os.path.join(OUT, "docs_inventory_summary.txt"), "w").write("\n".join(S) + "\n"); print("\n".join(S))
