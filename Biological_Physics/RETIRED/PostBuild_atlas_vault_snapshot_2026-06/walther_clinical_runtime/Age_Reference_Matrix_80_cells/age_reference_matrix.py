def _interp(bins, age, idx):
    """Linear interpolation in age along column idx of the bin tuples."""
    if age <= bins[0][0]:  return bins[0][idx]
    if age >= bins[-1][0]: return bins[-1][idx]
    for i in range(len(bins) - 1):
        a0, a1 = bins[i][0], bins[i + 1][0]
        if a0 <= age <= a1:
            w = (age - a0) / (a1 - a0) if a1 > a0 else 0.0
            return bins[i][idx] * (1 - w) + bins[i + 1][idx] * w
    return bins[-1][idx]


def age_ref_A(arch_key, age):
    """Return age-matched expected A_mean for class arch_key at the given age."""
    bins = AGE_REFERENCE.get(arch_key)
    if not bins: return None
    return _interp(bins, age, 1)  # column 1 = A_mean


def age_ref_sd(arch_key, age):
    """Return age-matched A_sd for class arch_key at the given age."""
    bins = AGE_REFERENCE.get(arch_key)
    if not bins: return None
    return _interp(bins, age, 2)  # column 2 = A_sd


def age_ref_percentiles(arch_key, age):
    """Return (p10, p25, p50, p75, p90) of A at the given age."""
    bins = AGE_REFERENCE.get(arch_key)
    if not bins: return None
    return tuple(_interp(bins, age, i) for i in (6, 7, 8, 9, 10))
